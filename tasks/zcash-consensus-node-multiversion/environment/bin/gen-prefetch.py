#!/usr/bin/env python3
"""Generate one dependency-graph stand-in per step, for the image's registry cache.

    gen-prefetch.py <step-Cargo.lock> <out-dir>

The agent's environment has no general network access, so every crate a build
can reach must already be in the image's CARGO_HOME. This script turns one
step's frozen Cargo.lock into a crate whose only purpose is to make
`cargo fetch` populate that cache:

  * Cargo.toml lists every registry and git package the lock names as a
    direct, renamed, exactly-pinned dependency, with `default-features =
    false`. Because they are all direct, nothing in the lock is unreachable
    and cargo cannot re-resolve a version upwards -- which matters here,
    because an unpinned re-resolve picks present-day releases that the era
    toolchain cannot parse. Because every package is named directly, no
    feature of a stand-in dependency is load-bearing, and turning the
    defaults off stops a default feature from demanding a crate the step's own
    graph never enabled.
  * Cargo.lock is the step's frozen lock with the workspace's own path members
    (the `zebra*` crates) replaced by this stand-in, so the checksums and the
    exact versions are the ones the step really compiles. It is written in
    lockfile v3: the image's cargo is 1.59, which does not read v4.
  * src/ is a stub: no implementation, no path members, nothing of the task.

The locks these are generated from are each step's own pinned skeleton,
`steps/<NN>/tests/assets/prefetch/skeleton/Cargo.lock` -- the dependency graph
the step's shipped verifier builds against. At step 01 it is byte-identical to
the seeded workspace's own Cargo.lock; the later steps' graphs are the ones the
step's instruction tells the candidate to reach.

The `zebra*` crates are not cacheable: they are the upstream
implementation of the task itself, they appear in these locks only as path
members, and this script refuses to bake them even if one ever gained a
registry source.
"""

import hashlib
import os
import re
import sys

STAND_IN = "prefetch-stand-in"

# The upstream artifact of this task: the Zebra node the candidate is asked to
# reimplement, published on crates.io from 1.0.0-beta.25 onward and reachable
# in principle as a registry package. Its source must not reach the cache.
FORBIDDEN = re.compile(r"^zebra", re.IGNORECASE)

HEADER_TOML = """\
# Generated by gen-prefetch.py from this step's frozen Cargo.lock.
# Not the task's code: a dependency-graph stand-in whose only purpose is
# to make `cargo fetch` populate the registry cache in the image being
# built, so a build there needs no mirror. Do not edit.

[package]
name = "{name}"
version = "0.0.0"
edition = "2018"
publish = false

# Standalone: must not be absorbed into any surrounding workspace.
[workspace]
"""

HEADER_LOCK = """\
# Generated by gen-prefetch.py. Do not edit.
# The step's frozen Cargo.lock with its workspace members replaced by
# the stand-in package, so `cargo fetch` resolves nothing and yanked
# releases the step really compiles stay reachable.
"""


def parse_lock(text):
    """Split a cargo lock into package blocks, keeping each block's text."""
    packages = []
    for block in re.split(r"(?m)^\[\[package\]\]$", text)[1:]:
        name = re.search(r'(?m)^name = "(.*)"$', block).group(1)
        version = re.search(r'(?m)^version = "(.*)"$', block).group(1)
        source = re.search(r'(?m)^source = "(.*)"$', block)
        packages.append({
            "name": name,
            "version": version,
            "source": source.group(1) if source else None,
            "text": block.strip("\n"),
        })
    return packages


def dep_key(dep):
    """A lock dependency string 'name' or 'name version' -> (name, version|None)."""
    parts = dep.split(" ", 1)
    return parts[0], (parts[1] if len(parts) > 1 else None)


def dep_lines(block):
    body = re.search(r"(?ms)^dependencies = \[\n(.*?)^\]$", block)
    if not body:
        return []
    return [d.strip().rstrip(",").strip('"') for d in body.group(1).splitlines() if d.strip()]


def rename_key(name, version):
    return re.sub(r"[^0-9A-Za-z]+", "_", f"{name}_{version}").strip("_")


def source_tag(source):
    """A short, stable discriminator for a package source.

    One lock can carry the same crate name at the same version from two
    sources -- step 05 does, with `equihash 0.1.0` both from the registry and
    from a librustzcash revision -- and the TOML key that renames it has to
    stay unique.
    """
    return hashlib.sha256(source.encode()).hexdigest()[:6]


def git_source(source):
    """git+https://host/path.git?rev=<asked>#<resolved> -> (url, kind, value).

    A tag source keeps its tag: the lock records the resolved sha, but a
    manifest written with `rev = <sha>` would not match the frozen lock and
    `--locked` would refuse it.
    """
    url_part, _, resolved = source[len("git+"):].partition("#")
    url, _, query = url_part.partition("?")
    for kind in ("tag", "branch", "rev"):
        m = re.search(r"(?:^|&)" + kind + r"=([^&]+)", query)
        if m:
            # The lock's fragment is the resolved revision; prefer it for rev
            # sources so the fetch is exact, keep the name for tag/branch.
            return url, kind, (resolved if kind == "rev" and resolved else m.group(1))
    return url, "rev", resolved


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip().splitlines()[2].strip())
    lock_path, out_dir = sys.argv[1], sys.argv[2]

    packages = parse_lock(open(lock_path).read())
    src = lambda p: p["source"] or ""  # noqa: E731
    local = [p for p in packages if p["source"] is None]
    registry = [p for p in packages if src(p).startswith("registry+")]
    git = [p for p in packages if src(p).startswith("git+")]
    other = [p for p in packages
             if p["source"] and not src(p).startswith(("registry+", "git+"))]
    if other:
        sys.exit(f"unsupported sources: {[p['source'] for p in other]}")

    forbidden = [p for p in registry + git if FORBIDDEN.match(p["name"])]
    if forbidden:
        sys.exit("refusing to cache the upstream artifact: "
                 + ", ".join(f"{p['name']} {p['version']}" for p in forbidden))

    kept = registry + git

    # Nothing kept may depend on a path member: the members are dropped, so a
    # dangling reference would make the lock unresolvable rather than merely
    # incomplete.
    dropped_names = {p["name"] for p in local}
    for p in kept:
        for dep in dep_lines(p["text"]):
            name, _ = dep_key(dep)
            if name in dropped_names:
                sys.exit(f"{p['name']} still depends on dropped path member {name}")

    # Two crates, two versions in one lock -> the shorter lock spelling is
    # ambiguous in the stand-in's dependency list, so disambiguate every edge.
    counts = {}
    for p in kept:
        counts[p["name"]] = counts.get(p["name"], 0) + 1

    deps = []
    for p in sorted(kept, key=lambda p: (p["name"], p["version"])):
        if counts[p["name"]] > 1:
            deps.append(f'"{p["name"]} {p["version"]}"')
        else:
            deps.append(f'"{p["name"]}"')

    # The rename key must be unique within the file: same name, same version,
    # different source is a real case here.
    keys = {}
    used = set()
    for p in sorted(kept, key=lambda p: (p["name"], p["version"], src(p))):
        key = rename_key(p["name"], p["version"])
        if key in used:
            key = f"{key}_{source_tag(p['source'])}"
        if key in used:
            sys.exit(f"cannot build a unique dependency key for {p['name']} {p['version']}")
        used.add(key)
        keys[(p["name"], p["version"], p["source"])] = key

    os.makedirs(os.path.join(out_dir, "src"), exist_ok=True)

    # --- Cargo.toml ---------------------------------------------------------
    lines = [HEADER_TOML.format(name=STAND_IN), "[dependencies]"]
    for p in sorted(kept, key=lambda p: keys[(p["name"], p["version"], p["source"])]):
        key = keys[(p["name"], p["version"], p["source"])]
        # `default-features = false` on every entry: what has to be in the cache
        # is the lock's package set, and every package of it is named here
        # directly, so no feature of a stand-in dependency is load-bearing. Left
        # on, a default feature can demand a crate the step's own graph never
        # enabled -- step 08's lock holds `hashbrown 0.11.2` with no
        # dependencies at all, and ahash only arrives with hashbrown's default
        # features, at a version that lock does not carry.
        if p["source"].startswith("git+"):
            url, kind, value = git_source(p["source"])
            lines.append(f'{key} = {{ package = "{p["name"]}", '
                         f'git = "{url}", {kind} = "{value}", default-features = false }}')
        else:
            lines.append(f'{key} = {{ package = "{p["name"]}", '
                         f'version = "={p["version"]}", default-features = false }}')
    open(os.path.join(out_dir, "Cargo.toml"), "w").write("\n".join(lines) + "\n")

    # --- Cargo.toml, patch table --------------------------------------------
    #
    # The ladder carries git pins in `[patch.crates-io]`, and a lock's git
    # entries only resolve against them: `zcash_primitives` asks for
    # `orchard = "0.0"` from the registry, and the lock's orchard is a git
    # revision the step's workspace patches in. Mirroring the table is what
    # lets the frozen resolution be reproduced instead of re-derived;
    # without it cargo stops with `no matching package named orchard found`.
    # No `default-features` here: a patch entry is not a dependency edge.
    patches = []
    seen_patch = set()
    for p in sorted(git, key=lambda p: p["name"]):
        if p["name"] in seen_patch:
            sys.exit(f"two git sources for {p['name']} in one lock: a patch table "
                     f"can only carry one of them")
        seen_patch.add(p["name"])
        url, kind, value = git_source(p["source"])
        patches.append(f'{p["name"]} = {{ git = "{url}", {kind} = "{value}" }}')
    if patches:
        lines = ["", "# The step's own `[patch.crates-io]` pins, mirrored.", "[patch.crates-io]"]
        lines += patches
        with open(os.path.join(out_dir, "Cargo.toml"), "a") as f:
            f.write("\n".join(lines) + "\n")

    # --- Cargo.lock ---------------------------------------------------------
    # Plain `cargo fetch` will rewrite this file whatever shape it is written
    # in -- a stand-in resolves the same packages but not the same per-package
    # edge lists, and cargo derives those itself. The lock's job is the package
    # set and the checksums; both come through untouched (measured on step 01:
    # 327 packages before the fetch and 327 after, none dropped, none added).
    lock = [HEADER_LOCK, "version = 3", "", "[[package]]",
            f'name = "{STAND_IN}"', 'version = "0.0.0"', "dependencies = ["]
    lock += [f" {d}," for d in deps]
    lock += ["]", ""]
    for p in sorted(kept, key=lambda p: (p["name"], p["version"], src(p))):
        lock += ["[[package]]", p["text"], ""]
    open(os.path.join(out_dir, "Cargo.lock"), "w").write("\n".join(lock))

    open(os.path.join(out_dir, "src", "lib.rs"), "w").write(
        "// Intentionally empty. See Cargo.toml.\n")

    print(f"{out_dir}: {len(kept)} packages cached "
          f"({len(registry)} registry, {len(git)} git), "
          f"{len(local)} path members left out")


if __name__ == "__main__":
    main()

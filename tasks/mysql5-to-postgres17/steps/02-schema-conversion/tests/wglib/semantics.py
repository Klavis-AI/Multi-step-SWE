"""What the schema *does*, asked the same way of both servers.

`schemagate` compares declarations: this column is `varchar(100)`, that one is
an identity column, this index is unique. Declarations are where a schema
migration is easy to fake and easy to get subtly wrong at the same time. A
column declared `bigint` holds every value the `int(11)` it replaced held and
silently accepts three thousand million more; a column with no collation is
case sensitive only because the cluster's default happened to be; a unique
index on `Email` is not the unique index on `Email(128)` it replaced.

So this module asks the *server* instead, in statements, and asks both servers
exactly the same ones. The plan is built from `schema-baseline.json`, which
means the questions are fixed before either tree is looked at, and the same
probe ids come out of the MySQL recording and the PostgreSQL scoring run.

**Nothing here touches a real table.** Every probe runs against a clone:
`CREATE TABLE x LIKE t` on MySQL, `CREATE TEMP TABLE x (LIKE t INCLUDING ALL)`
on PostgreSQL. Both copy columns, defaults, the auto-increment or identity
property, check constraints and indexes -- and neither copies foreign keys,
which is why the six foreign key probes are the only ones that go near the real
tables, and they run inside a transaction that is rolled back.

The pairing rule of the trap list applies inside the plan, not only around it:
every probe that expects a refusal has a sibling that expects the same
statement shape to be accepted. `over` is meaningless without `fits`, and
`intover` is meaningless without `int` -- a schema where every insert fails
would otherwise score full marks on enforcement.
"""

import re

# Integer ranges MySQL enforces once strict mode is on, which is the tree step 2
# is handed. The display width in `int(11)` is not a range and never was.
INT_RANGE = {
    "tinyint": (-128, 127),
    "smallint": (-32768, 32767),
    "mediumint": (-8388608, 8388607),
    "int": (-2147483648, 2147483647),
    "integer": (-2147483648, 2147483647),
    "bigint": (-9223372036854775808, 9223372036854775807),
}
INTEGER_TYPES = tuple(INT_RANGE)
REAL_TYPES = ("float", "double", "decimal", "numeric", "real")
TEXT_TYPES = ("char", "varchar", "tinytext", "text", "mediumtext", "longtext")
BOUNDED_TEXT = ("char", "varchar")

CLONE = "wg_probe_clone"

# A value that no seed row carries, for the probes that have to touch a real
# table. Far outside the seeded id space and outside every recorded string.
ORPHAN_ID = 987654321

_SAFE = re.compile(r"\A[A-Za-z0-9 _.@-]*\Z")


class Lit(object):
    """A literal rendered into the statement as written, not quoted."""

    def __init__(self, text):
        self.text = str(text)

    def __repr__(self):
        return "Lit(%s)" % self.text


def render(value):
    """One SQL literal, in the spelling both servers read the same way."""
    if isinstance(value, Lit):
        return value.text
    if value is None:
        return "NULL"
    text = str(value)
    if not _SAFE.match(text):
        # Every value in this plan is generated by this module, so an unsafe one
        # is a bug in the plan and not input to be escaped around.
        raise ValueError("probe value is not plain text: %r" % text)
    return "'%s'" % text


class Probe(object):
    __slots__ = ("id", "table", "kind", "spec")

    def __init__(self, probe_id, table, kind, **spec):
        self.id = probe_id
        self.table = table
        self.kind = kind
        self.spec = spec

    def __repr__(self):
        return "<Probe %s>" % self.id


# --------------------------------------------------------------- the values --

def column_kind(col):
    t = col["type"]
    if t in INT_RANGE:
        return "int"
    if t in REAL_TYPES:
        return "real"
    if t in TEXT_TYPES:
        return "text"
    return "other"


def text_value(col, seq):
    """A short distinct value that fits, whatever the column's limit is.

    Short on purpose: the shortest text column in this schema is `varchar(5)`,
    and a probe value that has to be truncated per column would stop being the
    same question asked of every column.
    """
    value = "wg%d" % seq
    limit = col.get("length")
    if limit is not None and limit < len(value):
        raise ValueError("column %s is too short for a probe value" % col["name"])
    return value


def column_value(col, seq):
    kind = column_kind(col)
    if kind == "int":
        return Lit(seq)
    if kind == "real":
        return Lit("%d.5" % seq)
    if kind == "text":
        return text_value(col, seq)
    raise ValueError("no probe value for %s %s" % (col["name"], col["type"]))


def full_row(table, seq):
    """Every column the server does not fill in for itself, with value `seq`.

    Auto-increment columns are left out: supplying one would be asking a
    different question, and the identity probes ask that one deliberately.
    """
    row = {}
    for col in table["columns"]:
        if col["auto_increment"]:
            continue
        row[col["name"]] = column_value(col, seq)
    return row


def _case_pair(col):
    """A mixed-case value that fits the column, and the same value case-swapped."""
    mixed = "AbQ"
    limit = col.get("length")
    if limit is not None and limit < len(mixed):
        raise ValueError("column %s is too short for a case probe" % col["name"])
    return mixed, mixed.swapcase()


# ----------------------------------------------------------------- the plan --

def build_plan(baseline):
    """Every probe, derived from the recorded MySQL schema alone."""
    plan = []
    for name in sorted(baseline["tables"]):
        table = baseline["tables"][name]
        cols = {c["name"]: c for c in table["columns"]}
        row1 = full_row(table, 1)

        # The control the whole table's enforcement probes are read against: a
        # row of ordinary values goes in.
        plan.append(Probe("row/%s" % name, name, "insert",
                          values=row1, expect="accepted"))

        for col in table["columns"]:
            cname = col["name"]
            kind = column_kind(col)
            if col["auto_increment"]:
                plan.append(Probe("identity/%s/%s" % (name, cname), name,
                                  "identity", column=cname, values=row1))
            if col.get("default") is not None:
                without = dict(row1)
                without.pop(cname, None)
                plan.append(Probe("default/%s/%s" % (name, cname), name,
                                  "default", column=cname, values=without))
            if kind == "int" and not col["auto_increment"]:
                low, high = INT_RANGE[col["type"]]
                plan.append(Probe("int/%s/%s" % (name, cname), name, "insert",
                                  values=dict(row1, **{cname: Lit(1)}),
                                  expect="accepted"))
                # The same value as a quoted string: what a PDO bind of a PHP
                # string looks like by the time the server sees it.
                plan.append(Probe("intq/%s/%s" % (name, cname), name, "insert",
                                  values=dict(row1, **{cname: "1"}),
                                  expect="accepted"))
                # The top of the MySQL column's range. `int` at 1 says nothing
                # about the width of the column that arrived: a `smallint`
                # standing in for `int(11)` accepts 1 and rejects 2147483648,
                # which is what `intover` asks, so without this probe narrowing
                # every integer column is behaviourally invisible. This is the
                # acceptance half of `intover`, one row down.
                plan.append(Probe("inthigh/%s/%s" % (name, cname), name,
                                  "insert",
                                  values=dict(row1, **{cname: Lit(high)}),
                                  expect="accepted"))
                plan.append(Probe("intover/%s/%s" % (name, cname), name,
                                  "insert",
                                  values=dict(row1, **{cname: Lit(high + 1)}),
                                  expect="rejected"))
            # Only the columns MySQL gives a real character limit. A `text`
            # column's 65535 is a byte budget, not a declared width, and no
            # faithful PostgreSQL schema bolts a check constraint onto `text`
            # to reproduce it.
            if col["type"] in BOUNDED_TEXT and col.get("length"):
                limit = col["length"]
                plan.append(Probe("fits/%s/%s" % (name, cname), name, "insert",
                                  values=dict(row1, **{cname: "x" * limit}),
                                  expect="accepted"))
                plan.append(Probe("over/%s/%s" % (name, cname), name, "insert",
                                  values=dict(row1,
                                              **{cname: "x" * (limit + 1)}),
                                  expect="rejected"))
            if kind == "text" and col.get("collation"):
                mixed, swapped = _case_pair(col)
                plan.append(Probe("case/%s/%s" % (name, cname), name, "case",
                                  column=cname,
                                  values=dict(row1, **{cname: mixed}),
                                  probe_value=swapped))

        for index in table["indexes"]:
            if not index.get("unique"):
                continue
            parts = index["parts"]
            keys = [p["column"] for p in parts]
            iid = "%s/%s" % (name, index["name"])
            row2 = full_row(table, 2)
            same = dict(row2)
            for key in keys:
                same[key] = row1[key]
            plan.append(Probe("unique-dup/%s" % iid, name, "pair",
                              first=row1, second=same, expect="rejected"))
            plan.append(Probe("unique-distinct/%s" % iid, name, "pair",
                              first=row1, second=row2, expect="accepted"))
            if len(parts) == 1 and column_kind(cols[keys[0]]) == "text":
                col = cols[keys[0]]
                mixed, swapped = _case_pair(col)
                plan.append(Probe("unique-case/%s" % iid, name, "pair",
                                  first=dict(row1, **{col["name"]: mixed}),
                                  second=dict(row2, **{col["name"]: swapped}),
                                  expect=None))
                prefix = parts[0].get("prefix")
                if prefix:
                    # Two values that agree up to the indexed prefix and differ
                    # one character later. A unique index on the whole column
                    # accepts both; MySQL's prefix index does not.
                    head = "p" * prefix
                    plan.append(Probe("unique-prefix/%s" % iid, name, "pair",
                                      first=dict(row1,
                                                 **{col["name"]: head + "a"}),
                                      second=dict(row2,
                                                  **{col["name"]: head + "b"}),
                                      expect="rejected"))

        for fk in table["foreign_keys"]:
            orphan = dict(full_row(table, 9))
            for key in fk["columns"]:
                orphan[key] = Lit(ORPHAN_ID)
            plan.append(Probe("fk-orphan/%s/%s" % (name, fk["name"]), name,
                              "orphan", values=orphan, expect="rejected"))
    return plan


# ------------------------------------------------------------- the executors --

class Executor(object):
    """The half-dozen statements a probe is made of, in one dialect.

    Subclasses render; the probe logic below is written once and runs on both.
    """

    def clone(self, table):
        raise NotImplementedError

    def drop_clone(self):
        raise NotImplementedError

    def empty(self):
        raise NotImplementedError

    def insert(self, values, table=None):
        """(ok, message). `table` None means the clone."""
        raise NotImplementedError

    def count_eq(self, column, value):
        raise NotImplementedError

    def read(self, column):
        raise NotImplementedError

    def count_rows(self, table):
        """Rows in a real table -- the orphan probe's check on its own rollback."""
        raise NotImplementedError

    def identity_mark(self, table):
        """Where the table's generated key stands, in whatever form restores it.

        A rollback returns the rows and does not return the number: both
        servers hand an auto-increment or identity value out before they know
        whether the statement will survive, and both leave the counter where
        the abandoned row left it. That is invisible while the probes are the
        only thing writing, and it is not invisible when the next writer is the
        application: its rows would carry keys one or two higher than the same
        requests produced against the server this is compared to. So the one
        probe that writes to a real table puts the counter back as well.
        """
        raise NotImplementedError

    def identity_restore(self, table, mark):
        raise NotImplementedError

    def transaction(self):
        """Context manager whose body is rolled back whatever happens."""
        raise NotImplementedError

    # ------------------------------------------------------------ rendering --
    @staticmethod
    def _columns(values):
        return sorted(values)

    def column_ident(self, name, table=None):
        """The column, spelled as *this* server has it.

        The plan carries the MySQL name. On MySQL that is the name. On
        PostgreSQL a migration is free to have folded `Username` to
        `username` -- which is what unquoted SQL in the application resolves
        to, and therefore the likeliest answer -- so a probe that emitted
        `"Username"` would fail on the most ordinary correct schema and the
        gate would be measuring quoting. Resolved per table by the subclass.
        """
        return self.ident(name)

    def insert_sql(self, target, values, table=None):
        names = self._columns(values)
        return "INSERT INTO %s (%s) VALUES (%s)" % (
            target,
            ", ".join(self.column_ident(n, table) for n in names),
            ", ".join(render(values[n]) for n in names))

    def ident(self, name):
        raise NotImplementedError


class MySQLExecutor(Executor):
    def __init__(self, conn):
        self.conn = conn
        self.cur = conn.cursor()
        self._clone = None

    def ident(self, name):
        return "`%s`" % name.replace("`", "``")

    def _run(self, sql):
        self.cur.execute(sql)

    def clone(self, table):
        self.drop_clone()
        self._run("CREATE TABLE %s LIKE %s" % (self.ident(CLONE),
                                               self.ident(table)))
        self._clone = table

    def drop_clone(self):
        self._run("DROP TABLE IF EXISTS %s" % self.ident(CLONE))
        self._clone = None

    def empty(self):
        self._run("DELETE FROM %s" % self.ident(CLONE))

    def insert(self, values, table=None):
        target = self.ident(table or CLONE)
        try:
            self._run(self.insert_sql(target, values, table or self._clone))
            return True, ""
        except Exception as exc:                      # pragma: no cover - dialect
            return False, str(exc)[:200]

    def count_eq(self, column, value):
        self._run("SELECT COUNT(*) FROM %s WHERE %s = %s"
                  % (self.ident(CLONE), self.ident(column), render(value)))
        return int(self.cur.fetchone()[0])

    def read(self, column):
        self._run("SELECT %s FROM %s" % (self.ident(column), self.ident(CLONE)))
        return [row[0] for row in self.cur.fetchall()]

    def count_rows(self, table):
        self._run("SELECT COUNT(*) FROM %s" % self.ident(table))
        return int(self.cur.fetchone()[0])

    def identity_mark(self, table):
        self._run("SELECT AUTO_INCREMENT FROM information_schema.TABLES"
                  " WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = %s"
                  % render(table))
        row = self.cur.fetchone()
        return None if row is None else row[0]

    def identity_restore(self, table, mark):
        if mark is None:
            return
        self._run("ALTER TABLE %s AUTO_INCREMENT = %d"
                  % (self.ident(table), int(mark)))

    def transaction(self):
        return _MySQLRollback(self.conn)


class PostgresExecutor(Executor):
    def __init__(self, conn, resolved):
        self.conn = conn
        self.conn.autocommit = True
        self.cur = conn.cursor()
        self.resolved = resolved      # {mysql table name: pgnames.Resolved}
        self._clone = None
        self._colmap = {}             # mysql table -> {folded name: real name}

    def _cols(self, table):
        if table not in self._colmap:
            res = self.resolved.get(table)
            found = {}
            if res is not None and res.found:
                from . import pgnames
                found = {k: v["name"]
                         for k, v in pgnames.columns_of(self.conn, res).items()}
            self._colmap[table] = found
        return self._colmap[table]

    def column_ident(self, name, table=None):
        # The clone is CREATE TEMP TABLE ... (LIKE real), so its columns are
        # spelled exactly as the real table's. Folded is the fallback because
        # it is what an unquoted CREATE TABLE produces and what the
        # application's own unquoted SQL resolves to.
        real = self._cols(table or self._clone).get(name.lower()) \
            if (table or self._clone) else None
        return self.ident(real or name.lower())

    def ident(self, name):
        return '"%s"' % name.replace('"', '""')

    def _run(self, sql):
        self.cur.execute(sql)

    def real(self, table):
        found = self.resolved.get(table)
        if not found or not found.found:
            raise KeyError(table)
        return found.qualified

    def clone(self, table):
        self.drop_clone()
        self._run("CREATE TEMP TABLE %s (LIKE %s INCLUDING ALL)"
                  % (self.ident(CLONE), self.real(table)))
        self._clone = table

    def drop_clone(self):
        self._run("DROP TABLE IF EXISTS %s" % self.ident(CLONE))
        self._clone = None

    def empty(self):
        self._run("DELETE FROM %s" % self.ident(CLONE))

    def insert(self, values, table=None):
        target = self.real(table) if table else self.ident(CLONE)
        try:
            self._run(self.insert_sql(target, values, table or self._clone))
            return True, ""
        except Exception as exc:
            # autocommit is on, so a failed statement leaves no aborted
            # transaction behind; the rollback is belt and braces for the
            # foreign key probes, which do open one.
            try:
                self.conn.rollback()
            except Exception:
                pass
            return False, str(exc).strip().splitlines()[0][:200]

    def count_eq(self, column, value):
        self._run("SELECT COUNT(*) FROM %s WHERE %s = %s"
                  % (self.ident(CLONE), self.column_ident(column),
                     render(value)))
        return int(self.cur.fetchone()[0])

    def read(self, column):
        self._run("SELECT %s FROM %s"
                  % (self.column_ident(column), self.ident(CLONE)))
        return [row[0] for row in self.cur.fetchall()]

    def count_rows(self, table):
        self._run("SELECT COUNT(*) FROM %s" % self.real(table))
        return int(self.cur.fetchone()[0])

    def identity_mark(self, table):
        """[(sequence, last_value, is_called)] for every column that owns one.

        The driver binds these rather than `render` building them, because the
        values are a schema-qualified table name and a sequence name that the
        server itself produced -- `render` is for the plan's own generated
        values and refuses anything it did not generate, which is the right
        answer there and the wrong one here.
        """
        real = self.real(table)
        self.cur.execute(
            "SELECT pg_get_serial_sequence(%s, a.attname)"
            " FROM pg_attribute a"
            " WHERE a.attrelid = %s::regclass AND a.attnum > 0"
            " AND NOT a.attisdropped", (real, real))
        seqs = [row[0] for row in self.cur.fetchall() if row[0]]
        marks = []
        for seq in seqs:
            # A sequence name from pg_get_serial_sequence is already quoted
            # where it needs to be; it is not a value, so it cannot be bound.
            self._run("SELECT last_value, is_called FROM %s" % seq)
            last, called = self.cur.fetchone()
            marks.append((seq, last, called))
        return marks

    def identity_restore(self, table, mark):
        for seq, last, called in (mark or ()):
            self.cur.execute("SELECT setval(%s, %s, %s)",
                             (seq, last, bool(called)))

    def sequence_marks(self):
        """[(sequence, last_value, is_called)] for every sequence in the database.

        The clones are `LIKE ... INCLUDING ALL`, and INCLUDING DEFAULTS copies a
        `serial` column's `nextval('<real>_id_seq')` as written: the clone
        draws its keys from the REAL table's sequence, and sequences are not
        transactional. An identity column gets a fresh sequence instead, so a
        schema that chose identity never noticed, and one that chose `serial`
        -- which the schema gate accepts -- would reach the corpus with every
        counter moved on by the probes. So the whole plan is bracketed: every
        persistent sequence is read before it and put back after it, whatever
        the default expression that reaches it looks like.
        """
        self.cur.execute(
            "SELECT c.oid::regclass::text FROM pg_class c"
            " WHERE c.relkind = 'S' AND c.relpersistence <> 't'"
            " ORDER BY 1")
        marks = []
        for (seq,) in self.cur.fetchall():
            try:
                self._run("SELECT last_value, is_called FROM %s" % seq)
                last, called = self.cur.fetchone()
            except Exception:
                continue
            marks.append((seq, last, called))
        return marks

    def sequence_restore(self, marks):
        for seq, last, called in (marks or ()):
            try:
                self.cur.execute("SELECT setval(%s, %s, %s)",
                                 (seq, last, bool(called)))
            except Exception:
                pass

    def transaction(self):
        return _PgRollback(self.conn)


# The two drivers do not spell autocommit the same way -- PyMySQL has a
# method, psycopg2 a bool property -- so each gets its own context manager
# rather than one that sets whichever attribute happens to be there and
# swallows the exception when it is the wrong kind. The orphan probe does not
# take the rollback on trust either: it counts the real table's rows either
# side (_answer_orphan), so a table whose engine cannot roll back is reported
# instead of quietly keeping the probe row.

class _MySQLRollback(object):
    """Whatever the body did, the server forgets it."""

    def __init__(self, conn):
        self.conn = conn
        self.was = None

    def __enter__(self):
        self.was = self.conn.get_autocommit()
        self.conn.autocommit(False)
        self.conn.begin()
        return self

    def __exit__(self, *exc):
        try:
            self.conn.rollback()
        finally:
            self.conn.autocommit(self.was)
        return False


class _PgRollback(object):
    """Whatever the body did, the server forgets it."""

    def __init__(self, conn):
        self.conn = conn
        self.was = None

    def __enter__(self):
        self.was = self.conn.autocommit
        self.conn.autocommit = False
        return self

    def __exit__(self, *exc):
        try:
            self.conn.rollback()
        finally:
            self.conn.autocommit = self.was
        return False


# -------------------------------------------------------------- the running --

def _answer_insert(ex, probe):
    ex.empty()
    ok, _ = ex.insert(probe.spec["values"])
    return "accepted" if ok else "rejected"


def _answer_case(ex, probe):
    ex.empty()
    ok, _ = ex.insert(probe.spec["values"])
    if not ok:
        return "rejected"
    return "match" if ex.count_eq(probe.spec["column"],
                                  probe.spec["probe_value"]) else "nomatch"


def _answer_default(ex, probe):
    ex.empty()
    ok, _ = ex.insert(probe.spec["values"])
    if not ok:
        return "rejected"
    rows = ex.read(probe.spec["column"])
    if len(rows) != 1:
        return "unreadable"
    value = rows[0]
    if value is None:
        return "value:NULL"
    if isinstance(value, (bytes, bytearray)):
        value = value.decode("utf-8", "replace")
    if isinstance(value, bool):
        # A server that turned the column into a boolean did not store what the
        # recording stored, and says so here rather than through str().
        return "value:bool:%s" % value
    # Trailing blanks are the one difference `char(n)` has by design on either
    # server, and this probe is about the default's value, not its padding.
    return "value:%s" % str(value).rstrip()


def _answer_identity(ex, probe):
    ex.empty()
    first, _ = ex.insert(probe.spec["values"])
    second, _ = ex.insert(probe.spec["values"])
    if not (first and second):
        return "rejected"
    values = ex.read(probe.spec["column"])
    if len(values) != 2 or any(v is None for v in values):
        return "missing"
    try:
        a, b = int(values[0]), int(values[1])
    except (TypeError, ValueError):
        return "unreadable"
    if a == b:
        return "same"
    return "increasing" if b > a else "decreasing"


def _answer_pair(ex, probe):
    ex.empty()
    ok, _ = ex.insert(probe.spec["first"])
    if not ok:
        return "first-rejected"
    ok, _ = ex.insert(probe.spec["second"])
    return "accepted" if ok else "rejected"


def _answer_orphan(ex, probe):
    # The only probe that writes to a real table rather than to a clone: a
    # foreign key is a property of the constraint's own table and does not
    # survive CREATE TABLE LIKE on MySQL. The write is undone by the
    # transaction -- and the row count either side says so, rather than the
    # answer resting on an engine that supports one.
    before = ex.count_rows(probe.table)
    mark = ex.identity_mark(probe.table)
    with ex.transaction():
        ok, _ = ex.insert(probe.spec["values"], table=probe.table)
    after = ex.count_rows(probe.table)
    ex.identity_restore(probe.table, mark)
    if after != before:
        return "leaked:%d" % (after - before)
    return "accepted" if ok else "rejected"


ANSWERERS = {
    "insert": _answer_insert,
    "case": _answer_case,
    "default": _answer_default,
    "identity": _answer_identity,
    "pair": _answer_pair,
    "orphan": _answer_orphan,
}


def run_plan(ex, plan, on_error="error"):
    """{probe id: answer}, every probe asked, nothing skipped.

    A probe that raises is recorded as an error rather than dropped: at
    recording time that is a plan bug worth seeing, and at scoring time it is a
    failure, which is the rule the gate module already states.
    """
    answers = {}
    by_table = {}
    for probe in plan:
        by_table.setdefault(probe.table, []).append(probe)
    for table in sorted(by_table):
        probes = by_table[table]
        cloned = True
        if any(p.kind != "orphan" for p in probes):
            try:
                ex.clone(table)
            except Exception as exc:
                cloned = False
                detail = "%s:%s" % (on_error, str(exc).strip()[:80])
        for probe in probes:
            if probe.kind != "orphan" and not cloned:
                answers[probe.id] = detail
                continue
            try:
                answers[probe.id] = ANSWERERS[probe.kind](ex, probe)
            except Exception as exc:
                answers[probe.id] = "%s:%s" % (on_error,
                                               str(exc).strip()[:80])
        try:
            ex.drop_clone()
        except Exception:
            pass
    return answers


# ------------------------------------------------------------- probe units --

# The grain the *instruction* states the requirement at. `instruction.md` says
# "For each of its 155 columns: ... it is nullable exactly where MySQL's is",
# and "each table must behave as the MySQL one behaves now" -- one requirement
# per column, per table, per unique index, per foreign key. Not one per probe.
#
# Scoring per probe over-credits, and the size of the gap was measured rather
# than guessed. `authoring/calibrate_pgloader.py` runs the platform's automated
# migrator, which maps all 87 `int` columns to `bigint` and the one `tinyint`
# to `boolean`, so every integer column in the schema it builds accepts values
# MySQL refuses and eight of them refuse values MySQL accepts. Per probe that
# schema scores **0.785**, because a column carries three acceptance probes for
# each refusal probe and any schema at all passes the acceptance ones. Per
# column it scores **0.482**, which is the true statement: 96 of its 153
# columns do not behave like the MySQL column they replaced.
#
# So a column is one check and it passes only if every probe about it agrees
# with MySQL. Three probes right out of four is not a migrated column; it is a
# column that accepts what it should accept and also accepts what it should
# refuse. The failing probes are all named in the check's detail, so nothing is
# lost for a trajectory read -- only the arithmetic changes.
_COLUMN_KINDS = ("int", "intq", "inthigh", "intover", "fits", "over",
                 "case", "default", "identity")
_UNIQUE_KINDS = ("unique-dup", "unique-distinct", "unique-case",
                 "unique-prefix")


def unit_id(probe_id):
    """`semantic/...` check id for the probe id `probe_id` belongs to."""
    kind, rest = probe_id.split("/", 1)
    if kind in _COLUMN_KINDS:
        return "semantic/column/%s" % rest
    if kind in _UNIQUE_KINDS:
        return "semantic/unique/%s" % rest
    if kind == "row":
        return "semantic/row/%s" % rest
    if kind == "fk-orphan":
        return "semantic/fk/%s" % rest
    raise AssertionError("no unit for probe kind %r" % kind)


def unit_ids(plan):
    """Every unit the plan asks about, first-seen order, no duplicates."""
    out, seen = [], set()
    for probe in plan:
        u = unit_id(probe.id)
        if u not in seen:
            seen.add(u)
            out.append(u)
    return out


# ---------------------------------------------------------------- the gate --

FIXTURE = "/tests/fixtures/schema-semantics.json"
BASELINE = "/tests/fixtures/schema-baseline.json"


def load(path=FIXTURE):
    import json as _json
    with open(path, "r", encoding="utf-8") as fh:
        return _json.load(fh)


def evaluate(conn, resolved, fixture=FIXTURE, baseline=BASELINE,
             family="semantics"):
    """One check per column, index, table and foreign key the recording covers.

    A unit passes when every probe about it answers what MySQL answered; see
    `unit_id` for why the grain is the column and not the probe.

    The denominator is the *recording*, read before the candidate's database is
    opened, so a schema that hides a table cannot shrink the question set -- a
    probe whose table did not resolve fails, like every other unanswerable
    check in this package.

    `resolved` is `pgnames.resolve_tables(conn, ...)`, so the tables are found
    the way the application finds them rather than at a schema this gate
    assumed.
    """
    from . import gate

    c = gate.Checks(family)
    try:
        rec = load(fixture)
        base = load(baseline)
    except (OSError, ValueError) as e:
        # 193 is the number of units the shipped 544-probe recording covers.
        # It is a literal because this is the branch where the recording would
        # not load, so there is nothing left to count -- and a denominator of 0
        # here would turn a missing fixture into a free 1.000.
        # `record_semantics.py` prints both counts; if either moves, so does
        # this.
        return gate.crashed(family, "no recorded semantics: %s" % e, 193)

    want = rec["answers"]
    plan = build_plan(base)
    ids = unit_ids(plan)

    # The plan and the recording have to be the same questions. They are built
    # by the same function from the same baseline, so a mismatch is this
    # package being internally inconsistent, not a candidate's doing -- and it
    # fails loudly rather than scoring whichever probes happen to line up.
    if sorted(p.id for p in plan) != sorted(want):
        c.error = ("plan/recording mismatch: %d planned, %d recorded"
                   % (len(plan), len(want)))
        c.fail_all(ids, c.error)
        return c

    try:
        ex = PostgresExecutor(conn, resolved)
    except Exception as e:
        c.error = "cannot open an executor: %s" % e
        c.fail_all(ids, c.error)
        return c

    # Read and put back around the whole plan: see `sequence_marks`. A database
    # whose sequences cannot be read is still probed; it just cannot be restored.
    try:
        marks = ex.sequence_marks()
    except Exception as e:
        marks = []
        c.note("sequences not marked before the probes: %s" % e)
    try:
        got = run_plan(ex, plan)
    finally:
        ex.sequence_restore(marks)

    # Collected first, added second, so the check order is the plan's order and
    # not the order the disagreements happened to arrive in.
    bad = {}
    for probe in plan:
        mine, theirs = got.get(probe.id), want[probe.id]
        if mine != theirs:
            bad.setdefault(unit_id(probe.id), []).append(
                "%s: MySQL answered %r, PostgreSQL answered %r"
                % (probe.id, theirs, mine))
    for uid in ids:
        why = bad.get(uid)
        c.add(uid, not why, "; ".join(why)[:400] if why else "")
    c.note("%d probe(s) over %d unit(s), recorded against MySQL %s"
           % (len(plan), len(ids), rec.get("server")))
    return c

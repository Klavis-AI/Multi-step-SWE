<?php
/**
 * The clean control for the dialect gate. Every statement here is PostgreSQL
 * 17, reached through every sink shape the gate knows, and the gate must
 * report nothing.
 *
 * Paired with dirty.php, which must be reported in full. A gate that passes
 * this file proves only that it is not reporting everything; a gate that
 * passes this file *and* catches every line of dirty.php is an instrument.
 */

namespace selftest;

class Clean
{
    /** jf::SQL(), the framework's own sink, with `?` placeholders. */
    public function statics($id, $name)
    {
        jf::SQL("SELECT ID, Username FROM users WHERE ID=? ORDER BY ID", $id);
        jf::SQL("UPDATE users SET Username=? WHERE ID=?", $name, $id);
        jf::SQL("DELETE FROM users WHERE ID=?", $id);
        jf::SQL("INSERT INTO users (Username) VALUES (?) RETURNING ID", $name);
        jf::SQL("INSERT INTO options (Name, Value) VALUES (?,?)
                 ON CONFLICT (Name) DO UPDATE SET Value = EXCLUDED.Value",
                $name, $id);
        jf::SQL("TRUNCATE TABLE sessions");
        jf::SQL("ALTER SEQUENCE users_id_seq RESTART WITH 1");
        jf::SQL("LOCK TABLE roles IN ACCESS EXCLUSIVE MODE");
    }

    /** Interpolation, so the holes carry identifiers. */
    public function interpolated($prefix, $id)
    {
        jf::SQL("SELECT Lft, Rght FROM {$prefix}roles WHERE ID=?", $id);
        jf::SQL("UPDATE {$prefix}roles SET Lft = Lft - 2 WHERE Lft > ?", $id);
        jf::SQL("SELECT string_agg(parent.Title, '/' ORDER BY parent.Lft)
                 AS Path FROM {$prefix}roles AS parent", $id);
    }

    /** Concatenation across many pieces, folded into one statement. */
    public function concatenated($table, $column)
    {
        $q = "SELECT S.*, U.* FROM " . $table . " AS S"
           . " LEFT JOIN users AS U ON (S." . $column . " = U.ID)"
           . " ORDER BY S.Time DESC LIMIT 50";
        jf::SQL($q);
    }

    /** A statement built up with `.=` before it reaches the sink. */
    public function accumulated($table)
    {
        $Query = "SELECT * FROM " . $table;
        $Query .= " ORDER BY ID DESC";
        $Query .= " LIMIT 20 OFFSET 40";
        jf::SQL($Query);
    }

    /** The driver methods, as the adapters and vendored libraries call them. */
    public function drivers($conn, $name)
    {
        $conn->query("SELECT count(*) FROM users");
        $conn->exec("CREATE INDEX IF NOT EXISTS stats_page_idx"
                    . " ON stats (left(Page, 255))");
        $conn->prepare("SELECT ID FROM users WHERE Username = $1");
        $conn->executeUpdate("UPDATE " . $name . " SET Value = $1 WHERE ID = $2");
        $this->SQL("CREATE TABLE IF NOT EXISTS stats ("
                   . " ID integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                   . " UserID integer NOT NULL,"
                   . " SessionID varchar(128) COLLATE \"C\" NOT NULL,"
                   . " Page text NOT NULL)");
    }

    /** Functions PostgreSQL has, so the catalog layer must accept them. */
    public function functions($id)
    {
        jf::SQL("SELECT coalesce(Title, '') FROM roles WHERE ID=?", $id);
        jf::SQL("SELECT extract(epoch FROM now())::bigint AS t");
        jf::SQL("SELECT lower(Username), length(Username) FROM users");
        jf::SQL("SELECT substring(Page FROM 1 FOR 255) FROM stats");
        jf::SQL("SELECT Title COLLATE \"C\" FROM roles ORDER BY 1");
    }

    /**
     * Not SQL, and the gate must not say it is. Each of these opens with a SQL
     * keyword and none of them is ever handed to a database.
     */
    public function prose()
    {
        $a = "Select a user to edit";
        $b = "Update database schema from ORM models";
        $c = "Create user result: " . $a;
        $d = "Replace";
        $e = "Update cookie " . $b . "=" . $c;
        $f = "set cURL username/password";
        return array($a, $b, $c, $d, $e, $f);
    }

    /**
     * SQL-shaped, and never handed to a database either: a string returned for
     * a caller to log, and a documentation sample. Reported as unreached, not
     * scored -- these are MySQL and the gate must still stay quiet.
     */
    public function unreached()
    {
        $sample = "SELECT * FROM `legacy` WHERE id=1 LIMIT 1";
        $help = "REPLACE INTO t (a) VALUES (1)";
        return $sample . "\n" . $help;
    }
}

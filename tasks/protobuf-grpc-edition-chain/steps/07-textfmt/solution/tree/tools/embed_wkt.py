#!/usr/bin/env python3
"""Embed the bundled well-known-type .proto sources as C string literals.

protoc ships google/protobuf/*.proto inside its own distribution and resolves
those imports without touching the filesystem. A compiler claiming parity with
a given protoc release must embed *that release's* copies: the sources change
between majors, which is exactly what makes the release train observable in
--include_imports output.

Usage: embed_wkt.py <wkt-root> <out.c>
"""
import os, sys


def c_escape(data):
    out = []
    for b in data:
        c = chr(b)
        if c == '\\':
            out.append('\\\\')
        elif c == '"':
            out.append('\\"')
        elif c == '\n':
            out.append('\\n"\n    "')
        elif c == '\t':
            out.append('\\t')
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append('\\%03o' % b)
    return ''.join(out)


def main():
    root, out_path = sys.argv[1], sys.argv[2]
    files = []
    for dirpath, _, names in os.walk(root):
        for n in sorted(names):
            if n.endswith('.proto'):
                full = os.path.join(dirpath, n)
                files.append((os.path.relpath(full, root).replace(os.sep, '/'), full))
    files.sort()
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/embed_wkt.py -- do not edit. */\n')
        f.write('#include "wkt.h"\n#include <string.h>\n\n')
        for i, (rel, full) in enumerate(files):
            with open(full, 'rb') as src:
                data = src.read()
            f.write('static const char wkt_%d[] =\n    "%s";\n\n' % (i, c_escape(data)))
        f.write('const WktFile wkt_files[] = {\n')
        for i, (rel, _) in enumerate(files):
            f.write('  { "%s", wkt_%d, sizeof(wkt_%d) - 1 },\n' % (rel, i, i))
        f.write('};\n')
        f.write('const int wkt_files_count = %d;\n\n' % len(files))
        f.write('const WktFile *wkt_lookup(const char *path) {\n')
        f.write('  for (int i = 0; i < wkt_files_count; i++)\n')
        f.write('    if (strcmp(wkt_files[i].path, path) == 0) return &wkt_files[i];\n')
        f.write('  return 0;\n}\n')
    print('embedded %d files -> %s' % (len(files), out_path))
    return 0


if __name__ == '__main__':
    sys.exit(main())

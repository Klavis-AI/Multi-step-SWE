#!/usr/bin/env bash
# Verifier for step 01-lane-geometry-queries. This header names the step so the ten
# generated copies of this script differ in SIZE as well as bytes. The
# verifier image's builder identifies build-context files by (relative
# path, size, mtime), and until 2026-10-21 several copies of test.sh
# shared all three while their bytes differed: the step-03 image then
# ran step 01's copy and the binding check below zeroed the step. See
# that check for the runtime half of this guard.

# --- verifier/step binding check -------------------------------------------
# /etc/harbor-step-id names the image; the literal below names this tests/ tree.
# They disagree only when the build context came from another step's cache
# entry, in which case every check below would grade the wrong milestone.
# Reported, not crashed: a non-zero exit makes Harbor skip the remaining steps
# and buries the fault under a second symptom. reward.json below therefore
# carries the number and nothing else: Harbor parses every value in it as a
# number, and a diagnostic string raises VerifierOutputParseError, which is
# itself a verifier exception -- Harbor aborts the remaining steps on it even
# with no min_reward configured. The diagnosis goes to step-mismatch.log.
__hb_want=01
__hb_got=$(cat /etc/harbor-step-id 2>/dev/null) || __hb_got=MISSING
if [ "$__hb_got" != "$__hb_want" ]; then
    __hb_msg="VERIFIER/STEP MISMATCH: image is step ${__hb_got}, /tests tree is step ${__hb_want}."
    printf '%s\n' "$__hb_msg" >&2
    mkdir -p /logs/verifier 2>/dev/null
    printf '%s\n' "$__hb_msg" > /logs/verifier/step-mismatch.log
    # Numeric only -- see the note above. The image and tests step ids are
    # already in step-mismatch.log and on stderr.
    printf '{"reward":0}\n' > /logs/verifier/reward.json
    exit 0
fi
unset __hb_want __hb_got __hb_msg
# --- end binding check ------------------------------------------------------
#
# Verifier entry point for ONE step of openscenario-engine-multiversion.
# Generated by misc/openscenario-engine-multiversion/build-package.sh; what
# differs between steps is assets/groups.txt, assets/cases/, assets/drivers/
# and the values substituted at the top. Never hand-edit a copy of this file.
#
# Runs in this step's verifier container on a fresh copy of /app. Nothing
# written here reaches the next step; only /logs/verifier is read back.

set -u
source /tests/helpers.sh

STEP=01
RELEASE=2.23.1

# --- budgets ---------------------------------------------------------------
# Every one of these is a CEILING that [steps.verifier].timeout_sec in
# task.toml is derived from, not a number copied from another task:
#
#   timeout_sec  >=  2*BUILD_BUDGET + DRIVER_BUDGET + CASE_WALL * CASE_TOTAL + SLACK
#   (BUILD_BUDGET twice: it is applied to the configure step and to the build
#    step as two separate timeouts, below.)
#
# build-package.sh computes that sum from this step's own case count and writes
# the result into task.toml, so the ceiling cannot drift away from the script.
BUILD_BUDGET=2400     # applied to cmake configure AND again to cmake build
DRIVER_BUDGET=300   # compiling every verifier-owned C driver
CASE_WALL=90           # hard wall for one case script
CASE_TIMEOUT=40     # hard wall for one product invocation inside a case
export CASE_TIMEOUT

log_dir=/tmp/esmini-verifier
scratch=/tmp/esmini-scratch
rm -rf -- "$log_dir" "$scratch"
mkdir -p "$log_dir" "$log_dir/case-logs" "$scratch"

app=/app
build_dir=$scratch/build
DRIVERS=$scratch/drivers
FIXTURES=/tests/assets/fixtures
export FIXTURES DRIVERS

# Diagnostic only: which shape the build took. Never affects a group name, a
# case count or the denominator.
build_mode=none

# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
# Declared here, populated from groups.txt further down. record() reads
# GROUP_KIND and GROUP_SHARE, and `set -u` makes an element read of an
# undeclared associative array a fatal error -- so the declarations have to
# precede the definition even though nothing populates them until later.
declare -a ALL_GROUPS=()
declare -A GROUP_WANT=()
declare -A GROUP_KIND=()
declare -A GROUP_SHARE=()

passed=0
total=0
gate_total=0
gate_failed=0
scored_total=0                   # how many groups are SCORED, from the manifest
scored_share_total=0
scored_share_passed=0
group_json=''
gate_fail_json=''
recorded=','
finished=0

# JSON string escape for the free-text diagnostics that end up in
# reward_details.json. A gate failure has to NAME its case and say why, so the
# reason text is emitted verbatim and must not be able to break the document.
jesc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

record() {  # record <group> <0=pass|1=fail> <detail>
    local name="$1" status="$2" detail="${3:-}" bit=0 kind share weight
    total=$((total + 1))
    if [ "$status" -eq 0 ]; then
        passed=$((passed + 1)); bit=1
    fi
    kind=${GROUP_KIND[$name]:-scored}
    share=${GROUP_SHARE[$name]:-0}
    if [ "$kind" = gate ]; then
        # The gate earns nothing. It only vetoes, and when it vetoes it says so
        # by name: a step reporting 0 without naming the group that zeroed it is
        # indistinguishable from a candidate that did nothing.
        gate_total=$((gate_total + 1))
        weight=0
        if [ "$bit" -eq 0 ]; then
            gate_failed=$((gate_failed + 1))
            gate_fail_json="${gate_fail_json}${gate_fail_json:+,}{\"group\":\"$(jesc "$name")\",\"reason\":\"$(jesc "${detail:-no diagnostic}")\"}"
        fi
    else
        scored_share_total=$((scored_share_total + share))
        [ "$bit" -eq 1 ] && scored_share_passed=$((scored_share_passed + share))
        weight=$(awk -v s="$share" -v t="$SHARE_SUM" \
            'BEGIN { if (t <= 0) printf "0.000000"; else printf "%.6f", s / t }')
    fi
    group_json="${group_json}${group_json:+,}\"$name\":{\"pass\":$bit,\"kind\":\"$kind\",\"weight\":$weight,\"detail\":\"$(jesc "$detail")\"}"
    recorded="${recorded}${name},"
    printf '%s %s [%s] %s\n' "$([ "$bit" -eq 1 ] && echo PASS || echo FAIL)" "$name" "$kind" "$detail" \
        >> "$log_dir/groups.txt"
}

write_details() {  # write_details <gate> <score> <reward>
    # scored_groups is the number of SCORED groups -- not the group total.
    # It was ${#ALL_GROUPS[@]} until 2026-09-21, a leftover from the additive
    # schema, which made it a duplicate of total_groups under a name using the
    # new model's central term. This file is the diagnostic authority, so a
    # reader debugging a veto must not be told that every group is scored when
    # only the `scored` ones are.
    # share_sum and scored_share_passed are emitted so `score` is checkable
    # from the file itself: score == scored_share_passed / share_sum.
    printf '{"step":"%s","release":"%s","build_mode":"%s","reward":%s,"gate":{"passed":%s,"groups":%s,"failed":[%s]},"score":%s,"scored_groups":%s,"scored_share_passed":%s,"share_sum":%s,"passed_groups":%s,"total_groups":%s,"kinds":{%s},"groups":{%s}}\n' \
        "$STEP" "$RELEASE" "$build_mode" "$3" "$1" "$gate_total" "$gate_fail_json" \
        "$2" "$scored_total" "$scored_share_passed" "$SHARE_SUM" "$passed" "$total" \
        "$kind_json" "$group_json" > /logs/verifier/reward_details.json
}

finish() {  # finish
    local gate score reward
    finished=1
    cp "$log_dir/groups.txt" /logs/verifier/groups.txt 2>/dev/null || true
    mkdir -p /logs/verifier/failed
    if [ -f "$log_dir/groups.txt" ]; then
        while read -r status name _rest; do
            [ "$status" = FAIL ] || continue
            [ -f "$log_dir/case-logs/$name.log" ] && \
                tail -c 20000 "$log_dir/case-logs/$name.log" > "/logs/verifier/failed/$name.log"
        done < "$log_dir/groups.txt"
    fi
    for b in build configure drivers assets; do
        [ -s "$log_dir/$b.log" ] && tail -c 20000 "$log_dir/$b.log" > "/logs/verifier/$b.log"
    done

    # reward = gate x score.
    #
    #   gate   1 only when EVERY gate group passed. Gate groups are proof of
    #          life and inherited regression; they earn nothing and exist to
    #          veto. One failure zeroes the step however good the new work is.
    #   score  the share-weighted pass fraction over the SCORED groups alone.
    #          Shares are integers in groups.txt and normalised here, so the
    #          weights sum to exactly 1.0 with no hand-written rounding.
    #
    # A no-op preserves the inherited behaviour, so gate = 1, and implements no
    # new capability, so score = 0: the step is exactly 0. There is no per-step
    # "no-op ceiling" to compute and no inherited share to subtract.
    # The denominator is SHARE_SUM, read from the manifest, NOT the shares
    # actually recorded. on_exit backfills every group the run never reached as
    # a failure, so today the two are equal -- but if that backfill ever stops
    # covering a path, dividing by the recorded total would silently RAISE the
    # score of an aborted run: one passing group out of fourteen would report
    # 1.000000. Dividing by the manifest total makes an unreached group score
    # zero, which is the only safe reading.
    gate=$([ "$gate_failed" -eq 0 ] && echo 1 || echo 0)
    score=$(awk -v n="$scored_share_passed" -v d="$SHARE_SUM" \
        'BEGIN { if (d <= 0) printf "0.000000"; else printf "%.6f", n / d }')
    reward=$(awk -v g="$gate" -v s="$score" 'BEGIN { printf "%.6f", g * s }')
    write_details "$gate" "$score" "$reward"
    report "$reward"
}

# ---------------------------------------------------------------------------
# Group declaration.
#
# assets/groups.txt lists every group, its case count, its KIND and its share:
#
#   gate    proof of life (the candidate builds, the artifacts start) plus one
#           deterministic end-to-end path through each milestone this step
#           carries forward. Binary as a set; earns nothing; share is '-'.
#   scored  this step's new capability. Integer shares, normalised here.
#
# The kind is not a comment. It selects which of the two terms the group feeds,
# and mis-declaring one is the expensive mistake in this model: a
# new-capability group declared gate becomes an unpriced veto, and a gate group
# declared scored both stops vetoing and hands a no-op free credit.
# ---------------------------------------------------------------------------
CASE_TOTAL=0
SHARE_SUM=0
while read -r gname gcount gkind gshare; do
    case "$gname" in ''|\#*) continue ;; esac
    ALL_GROUPS+=("$gname")
    GROUP_WANT["$gname"]=$gcount
    GROUP_KIND["$gname"]=$gkind
    case "$gkind" in
        scored) GROUP_SHARE["$gname"]=$gshare; SHARE_SUM=$((SHARE_SUM + gshare))
                scored_total=$((scored_total + 1)) ;;
        *)      GROUP_SHARE["$gname"]=0 ;;
    esac
    CASE_TOTAL=$((CASE_TOTAL + gcount))
done < /tests/assets/groups.txt

kind_json=$(awk '$1 !~ /^#/ && NF >= 3 { c[$3]++ } END {
    s = ""
    n = split("gate scored", order, " ")
    for (i = 1; i <= n; i++) if (order[i] in c) s = s (s ? "," : "") "\"" order[i] "\":" c[order[i]]
    print s
}' /tests/assets/groups.txt)

fail_everything() {  # fail_everything <reason>
    : > "$log_dir/groups.txt"
    passed=0; total=0; gate_total=0; gate_failed=0
    scored_share_total=0; scored_share_passed=0
    group_json=''; gate_fail_json=''; recorded=','
    local g
    for g in "${ALL_GROUPS[@]}"; do record "$g" 1 "$1"; done
    finish
}

# A crash, kill or unexpected exit still produces a complete scorecard.
on_exit() {
    [ "$finished" -eq 0 ] || return 0
    local g
    for g in "${ALL_GROUPS[@]}"; do
        case "$recorded" in *",$g,"*) continue ;; esac
        record "$g" 1 "verifier-aborted-before-this-group"
    done
    finish
}
trap on_exit EXIT

: > "$log_dir/groups.txt"

# ---------------------------------------------------------------------------
# Asset integrity. A corrupt case corpus must fail every group rather than hand
# out free points, so it is a prerequisite and not a group of its own.
# ---------------------------------------------------------------------------
( cd /tests/assets && sha256sum -c SHA256SUMS ) > "$log_dir/assets.log" 2>&1
assets_ok=$?
case_files=$(find /tests/assets/cases -type f -name '*.sh' | wc -l)
expected_cases=$(cat /tests/assets/CASE_COUNT)
printf 'assets sha check=%s case-files=%s declared-in-groups.txt=%s CASE_COUNT=%s groups=%s\n' \
    "$assets_ok" "$case_files" "$CASE_TOTAL" "$expected_cases" "${#ALL_GROUPS[@]}" \
    >> "$log_dir/assets.log"
if [ "$assets_ok" -ne 0 ] || [ "$case_files" != "$expected_cases" ] \
   || [ "$CASE_TOTAL" != "$expected_cases" ] || [ "${#ALL_GROUPS[@]}" -eq 0 ]; then
    fail_everything "verifier case corpus failed its integrity check"
fi
# Every declared group must have exactly the case files groups.txt claims, or a
# group could silently score on fewer cases than it was reviewed for.
for g in "${ALL_GROUPS[@]}"; do
    have=$(find "/tests/assets/cases/$g" -maxdepth 1 -type f -name '*.sh' 2>/dev/null | wc -l)
    if [ "$have" != "${GROUP_WANT[$g]}" ]; then
        printf 'group %s: %s case files on disk, groups.txt declares %s\n' \
            "$g" "$have" "${GROUP_WANT[$g]}" >> "$log_dir/assets.log"
        fail_everything "verifier case corpus failed its integrity check"
    fi
done

# ---------------------------------------------------------------------------
# Build the candidate. /app is untrusted candidate data: never follow a symlink
# out of it, and write build output only into the throw-away scratch tree.
#
# The build command below is the one TEST_INTERFACE.md declares. It is a
# CONTRACT, not a preference: the candidate is free to restructure the project
# however it likes as long as this exact invocation still produces the
# documented binaries and shared libraries.
# ---------------------------------------------------------------------------

build_ok=1
if [ -L "$app" ] || [ ! -f "$app/CMakeLists.txt" ]; then
    echo "no /app/CMakeLists.txt" > "$log_dir/configure.log"
else
    build_mode=cmake
    # Build output from the candidate's own session is not evidence. Upstream's
    # CMake writes executables and shared libraries into <source>/bin, so a
    # stale bin/ -- or one a candidate committed instead of building -- would be
    # indistinguishable from this run's output to the artifact search below.
    # Removing them means every artifact graded here was produced by the build
    # command in TEST_INTERFACE.md, from the sources in /app, in this container.
    rm -rf -- "$app/bin" "$app/build" "$app/cmake_build" 2>/dev/null || true
    # Upstream downloads its optional externals unless the destination already
    # exists. Every one of them is switched off in the profile below, but at
    # some releases the download guard is not gated on the switch, so the
    # destinations are pre-created empty. This keeps the grading build offline
    # and deterministic; it adds no headers and no libraries.
    for __d in OSI OpenSceneGraph SUMO googletest osi osg sumo proj implot; do
        mkdir -p "$app/externals/$__d/linux" 2>/dev/null || true
    done
    mkdir -p "$app/resources/models" 2>/dev/null || true
    unset __d
    ( cd "$app" && timeout "$BUILD_BUDGET" cmake \
        -S "$app" -B "$build_dir" \
        --no-warn-unused-cli -Wno-dev \
        -DCMAKE_BUILD_TYPE=Release \
        -DFORCE_DOWNLOAD_BINARIES=False \
        -DDOWNLOAD_EXTERNALS=False \
        -DUSE_OSG=False \
        -DUSE_OSI=False \
        -DUSE_SUMO=False \
        -DUSE_GTEST=False \
        -DUSE_IMPLOT=False \
        -DUSE_PROJ=False \
        -DENABLE_SANITIZERS=False \
        -DENABLE_INCLUDE_WHAT_YOU_USE=False
    ) > "$log_dir/configure.log" 2>&1
    configure_ok=$?
    printf 'cmake configure status=%s\n' "$configure_ok" >> "$log_dir/configure.log"
    if [ "$configure_ok" -eq 0 ]; then
        ( cd "$app" && timeout "$BUILD_BUDGET" cmake --build "$build_dir" --parallel 4 \
              --target esmini esmini-dyn esminiLib esminiRMLib odrplot dat2csv ) \
            > "$log_dir/build.log" 2>&1
        build_ok=$?
    else
        echo "configure failed; skipping compile" > "$log_dir/build.log"
    fi
fi
printf 'cmake build status=%s\n' "$build_ok" >> "$log_dir/build.log"

# ---------------------------------------------------------------------------
# Locate the documented artifacts. Upstream puts them in <source>/bin; a
# candidate that moved them is still accepted as long as they are somewhere
# under /app or the build tree, because their LOCATION is not the capability
# under test. Their NAMES are, and those are fixed in TEST_INTERFACE.md.
# ---------------------------------------------------------------------------
find_artifact() {  # find_artifact <name> [type]
    local n="$1" t="${2:-f}" p
    for p in "$app/bin/$n" "$build_dir/$n"; do
        [ -e "$p" ] && { printf '%s\n' "$p"; return 0; }
    done
    p=$(find "$app/bin" "$build_dir" "$app" -maxdepth 6 -name "$n" -type "$t" \
            -not -path '*/externals/*' 2>/dev/null | head -1)
    [ -n "$p" ] && { printf '%s\n' "$p"; return 0; }
    return 1
}

ESMINI=$(find_artifact esmini) || ESMINI=/nonexistent/esmini
ESMINI_DYN=$(find_artifact esmini-dyn) || ESMINI_DYN=/nonexistent/esmini-dyn
ODRPLOT=$(find_artifact odrplot) || ODRPLOT=/nonexistent/odrplot
DAT2CSV=$(find_artifact dat2csv) || DAT2CSV=/nonexistent/dat2csv
ESMINI_LIB=$(find_artifact libesminiLib.so) || ESMINI_LIB=
ESMINI_RM_LIB=$(find_artifact libesminiRMLib.so) || ESMINI_RM_LIB=
LIBDIR=$scratch/lib
mkdir -p "$LIBDIR"
for l in "$ESMINI_LIB" "$ESMINI_RM_LIB"; do
    [ -n "$l" ] && [ -f "$l" ] && cp "$l" "$LIBDIR/" 2>/dev/null
done
# The candidate's own shared libraries may sit next to other build output it
# needs at load time; keep those directories on the search path too.
for l in "$ESMINI_LIB" "$ESMINI_RM_LIB"; do
    [ -n "$l" ] && LIBDIR="$LIBDIR:$(dirname "$l")"
done
RESOURCES=$app/resources
export ESMINI ESMINI_DYN ODRPLOT DAT2CSV LIBDIR RESOURCES
{
    printf 'esmini=%s\n'       "$ESMINI"
    printf 'odrplot=%s\n'      "$ODRPLOT"
    printf 'dat2csv=%s\n'      "$DAT2CSV"
    printf 'esmini-dyn=%s\n'   "$ESMINI_DYN"
    printf 'esminiLib=%s\n'    "${ESMINI_LIB:-MISSING}"
    printf 'esminiRMLib=%s\n'  "${ESMINI_RM_LIB:-MISSING}"
} >> "$log_dir/build.log"

# ---------------------------------------------------------------------------
# Compile the verifier-owned drivers against the candidate's headers and shared
# libraries. Each driver is compiled on its own so one that does not typecheck
# costs only the groups whose cases call it, and never the whole step.
#
# C++17, not C. Upstream's own headers are not C translation units at the early
# releases of this ladder -- esminiLib.hpp declares default arguments
# (`SE_OSIFileWrite(bool flush = false)`) and esminiRMLib.hpp uses `bool`
# without including <stdbool.h> -- so a C driver would fail against the real
# release and the contract would be unsatisfiable. Both headers compile clean
# as C++17 at every tag in the ladder. The C ABI claim is still checked, but
# by reading the exported symbol names out of the .so, which is where that
# claim actually lives.
# ---------------------------------------------------------------------------
mkdir -p "$DRIVERS"
# The headers' FILE NAMES are the contract; their directories are discovered,
# so a candidate that reorganises the tree is not punished for it. externals/
# is excluded so a vendored copy of someone else's header cannot win the race.
find_header() {  # find_header <name>
    find "$app" -maxdepth 6 -name "$1" -type f -not -path '*/externals/*' \
        -printf '%h\n' 2>/dev/null | head -1
}
inc_lib=$(find_header esminiLib.hpp)
inc_rm=$(find_header esminiRMLib.hpp)
printf 'esminiLib.hpp dir=%s\nesminiRMLib.hpp dir=%s\n' \
    "${inc_lib:-MISSING}" "${inc_rm:-MISSING}" >> "$log_dir/build.log"
: > "$log_dir/drivers.log"
driver_deadline=$(( $(date +%s) + DRIVER_BUDGET ))
for src in /tests/assets/drivers/*.cpp; do
    [ -e "$src" ] || break
    base=$(basename "$src" .cpp)
    if [ "$(date +%s)" -ge "$driver_deadline" ]; then
        printf '%s: SKIPPED, driver budget exhausted\n' "$base" >> "$log_dir/drivers.log"
        continue
    fi
    libs=""
    # LIBDIR is a COLON-SEPARATED list (this project installs the two shared
    # libraries into different directories), so it can never be pasted in front
    # of a file name. The first entry is the scratch directory both libraries
    # were copied into just above, and that is the one -L below also uses.
    libstage=${LIBDIR%%:*}
    [ -f "$libstage/libesminiLib.so" ]   && libs="$libs -lesminiLib"
    [ -f "$libstage/libesminiRMLib.so" ] && libs="$libs -lesminiRMLib"
    printf '=== %s ===\n' "$base" >> "$log_dir/drivers.log"
    g++ -std=c++17 -O0 -o "$DRIVERS/$base" "$src" \
        ${inc_lib:+-I"$inc_lib"} ${inc_rm:+-I"$inc_rm"} \
        -L"$libstage" $libs -lm -lpthread \
        >> "$log_dir/drivers.log" 2>&1 \
        || printf '%s: COMPILE FAILED\n' "$base" >> "$log_dir/drivers.log"
done

# ---------------------------------------------------------------------------
# Run the groups. A group passes only when every one of its cases passes.
# ---------------------------------------------------------------------------
run_group() {  # run_group <name>
    local g="$1" glog="$log_dir/case-logs/$g.log" c cname rc failures=0 ran=0
    : > "$glog"
    for c in $(find "/tests/assets/cases/$g" -maxdepth 1 -type f -name '*.sh' | sort); do
        cname=$(basename "$c" .sh)
        ran=$((ran + 1))
        WORK=$scratch/work/$g/$cname
        rm -rf -- "$WORK"; mkdir -p "$WORK"
        printf '\n===== case %s/%s =====\n' "$g" "$cname" >> "$glog"
        ( export WORK; cd "$WORK" && timeout "$CASE_WALL" bash "$c" ) >> "$glog" 2>&1
        rc=$?
        # `--` is required: the format starts with a dash, so without it bash
        # reads "-----" as an option bundle, prints "printf: --: invalid option"
        # to the verifier's stderr and writes no exit line at all. $rc is
        # already captured above, so the grading was never affected -- but the
        # per-case exit status was missing from every group log, which is the
        # one place a failed case is diagnosed from.
        printf -- '----- case %s/%s exit=%s\n' "$g" "$cname" "$rc" >> "$glog"
        [ "$rc" -eq 0 ] || failures=$((failures + 1))
    done
    # An executed-count assertion: a group that silently ran fewer cases than
    # it was reviewed for must fail rather than score on the subset.
    if [ "$ran" != "${GROUP_WANT[$g]}" ]; then
        record "$g" 1 "ran $ran of ${GROUP_WANT[$g]} declared cases"
        return
    fi
    if [ "$failures" -eq 0 ]; then
        record "$g" 0 "$ran/$ran cases"
    else
        record "$g" 1 "$((ran - failures))/$ran cases"
    fi
}

for g in "${ALL_GROUPS[@]}"; do
    run_group "$g"
done

finish

# size-stamp 01 (verifier-build identity; see the header): ----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

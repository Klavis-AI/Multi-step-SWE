def _match(rel, pattern):
    """Segment-aware glob: ``*`` stops at ``/``, ``**`` crosses it."""
    rparts = rel.replace(os.sep, "/").split("/")
    pparts = pattern.split("/")

    def walk(i, j):
        while j < len(pparts):
            if pparts[j] == "**":
                for k in range(i, len(rparts) + 1):
                    if walk(k, j + 1):
                        return True
                return False
            if i >= len(rparts) or not fnmatch.fnmatch(rparts[i], pparts[j]):
                return False
            i += 1
            j += 1
        return i == len(rparts)

    return walk(0, 0)


def _match_any(rel, patterns):
    return any(_match(rel, p) for p in patterns)


def _walk(tree, patterns):
    for base, dirs, files in os.walk(tree):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for f in sorted(files):
            if not f.endswith(".py"):
                continue
            rel = os.path.relpath(os.path.join(base, f), tree)
            rel = rel.replace(os.sep, "/")
            if _match_any(rel, patterns):
                yield rel



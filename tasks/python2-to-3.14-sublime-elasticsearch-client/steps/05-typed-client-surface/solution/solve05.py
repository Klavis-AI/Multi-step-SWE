# EXTRA: the edits that are not signatures.
#
# Three kinds, and the instruction owes the reader all three:
#
#   * imports and declarations -- `__all__` where a module re-exports, a
#     class-level annotation where two branches assign the same attribute, a
#     `Protocol` or `TypedDict` where a duck type was never written down;
#   * renames -- a local rebound to a second type is two variables wearing one
#     name, and the checker is the first reader to say so out loud;
#   * `cast` -- exactly where the code is genuinely dynamic, and nowhere else.
#     Each one is commented in place with what it asserts and why the checker
#     cannot see it.
#
# Nothing here changes behaviour. The two places that come closest are called
# out in the comments: `PoolingConnection.__init__`, whose `*args` could only
# ever have been `(host, port)`, and `thrift.py`, where the inner handler
# shadowed the name the outer one re-raises -- a `NameError` waiting on a
# socket close failure, which the checker found and a rename fixes.
# --------------------------------------------------------------------------


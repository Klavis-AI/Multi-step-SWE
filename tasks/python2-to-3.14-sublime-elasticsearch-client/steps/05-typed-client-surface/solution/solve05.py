def _final_scan(tree):
    """What is *left*, said by re-reading the finished tree.

    Two questions the edit list cannot answer: is any site in scope still
    unannotated, and does any annotated file still lack the future import.
    """
    bad = []
    for rel in _walk(tree, _OWN_SURFACE):
        path = os.path.join(tree, rel)
        src = io.open(path, encoding="utf-8").read()
        for site in sites(src, rel, _match_any(rel, _TYPED_LIB)):
            bad.append("%s::%s %s %s" % (rel, site.qual, site.kind,
                                         site.arg or ""))
        parsed = ast.parse(src)
        annotated = any(
            getattr(n, "returns", None) is not None
            or isinstance(n, ast.AnnAssign)
            or any(a.annotation is not None
                   for a in (list(getattr(n.args, "posonlyargs", []))
                             + list(n.args.args) + list(n.args.kwonlyargs)
                             + [x for x in (n.args.vararg, n.args.kwarg) if x]))
            for n in ast.walk(parsed)
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef,
                              ast.AnnAssign)))
        if annotated and FUTURE not in src:
            bad.append("%s carries annotations without the future import"
                       % rel)
    return bad


def main(argv):
    if len(argv) != 1:
        sys.stderr.write("usage: solve05.py <tree>\n")
        return 2
    tree = argv[0]
    if not os.path.isdir(tree):
        sys.stderr.write("solve05: %s is not a directory\n" % tree)
        return 2
    touched = 0
    missing = []
    for rel in _walk(tree, _OWN_SURFACE):
        path = os.path.join(tree, rel)
        src = io.open(path, encoding="utf-8").read()
        out, miss = annotate(src, rel, False)
        missing += miss
        if out != src:
            io.open(path, "w", encoding="utf-8").write(out)
            touched += 1
    if missing:
        sys.stderr.write("solve05: %d sites the table does not cover; "
                         "the tree is not the one this solver was written "
                         "for\n" % len(missing))
        for site in missing[:20]:
            sys.stderr.write("    %s::%s %s %s\n"
                             % (site.rel, site.qual, site.kind,
                                site.arg or ""))
        return 1
    if not touched:
        sys.stderr.write("solve05: nothing was edited\n")
        return 1
    left = _final_scan(tree)
    if left:
        sys.stderr.write("solve05: %d sites left after the pass\n"
                         % len(left))
        for line in left[:20]:
            sys.stderr.write("    %s\n" % line)
        return 1
    sys.stderr.write("solve05: annotated %d files\n" % touched)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

PUBLIC_DUNDERS = ("__init__", "__enter__", "__exit__", "__iter__",
                  "__next__", "__call__")


Site = collections.namedtuple(
    "Site", "rel qual name kind arg lineno col default bases decorators")


def public(name):
    return not name.startswith("_") or name in PUBLIC_DUNDERS


def _defaults_map(args):
    """arg name -> the source of its default, or None."""
    out = {}
    pos = list(getattr(args, "posonlyargs", [])) + list(args.args)
    first = len(pos) - len(args.defaults)
    for i, a in enumerate(pos):
        out[a.arg] = args.defaults[i - first] if i >= first else None
    for a, d in zip(args.kwonlyargs, args.kw_defaults):
        out[a.arg] = d
    return out


def sites(src, rel, all_defs=False):
    """Every annotation this file needs.

    ``all_defs`` widens the walk from the AST gate's scope (public defs at
    module or class level) to every ``def`` in the file, nested and private
    included. The client core needs the wider one: the AST gate is not the
    only reader there, and a strict checker counts an unannotated inner
    helper as untyped and then refuses every call to it.
    """
    tree = ast.parse(src)

    def walk_defs(node, prefix, top):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.ClassDef):
                yield from walk_defs(child, prefix + child.name + ".", top)
            elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                yield child, prefix, top
                if all_defs:
                    yield from walk_defs(child, prefix + child.name + ".",
                                         False)
            elif all_defs and isinstance(child, (ast.If, ast.Try,
                                                 ast.With, ast.For,
                                                 ast.While)):
                yield from walk_defs(child, prefix, top)

    for node, prefix, top in walk_defs(tree, "", True):
        if not all_defs and not (top and public(node.name)):
            continue
        qual = prefix + node.name
        cls = prefix.rstrip(".").rsplit(".", 1)[-1] if prefix else None
        bases = (cls,) if cls else ()
        decs = tuple(ast.unparse(d) for d in node.decorator_list)
        args = node.args
        defaults = _defaults_map(args)
        every = (list(getattr(args, "posonlyargs", [])) + list(args.args)
                 + list(args.kwonlyargs))
        every = [(a, a.arg) for a in every]
        if args.vararg:
            every.append((args.vararg, "*" + args.vararg.arg))
        if args.kwarg:
            every.append((args.kwarg, "**" + args.kwarg.arg))
        for i, (a, shown) in enumerate(every):
            if i == 0 and a.arg in ("self", "cls"):
                continue
            if a.annotation is not None:
                continue
            d = defaults.get(a.arg)
            yield Site(rel, qual, node.name, "arg", shown, a.lineno,
                       a.end_col_offset,
                       ast.unparse(d) if d is not None else "-",
                       bases, decs)
        if node.returns is None and node.name != "__init__":
            yield Site(rel, qual, node.name, "return", None, node.lineno,
                       None, "-", bases, decs)


def header_colon(src, lineno, col):
    """Byte position of the ``:`` that ends a ``def``'s header."""
    lines = src.splitlines(True)
    offsets = [0]
    for ln in lines:
        offsets.append(offsets[-1] + len(ln))
    start = offsets[lineno - 1] + col
    depth = 0
    readline = io.StringIO(src).readline
    for tok in tokenize.generate_tokens(readline):
        pos = offsets[tok.start[0] - 1] + tok.start[1]
        if pos < start or tok.type != tokenize.OP:
            continue
        if tok.string in "([{":
            depth += 1
        elif tok.string in ")]}":
            depth -= 1
        elif tok.string == ":" and depth == 0:
            return tok.start[0], tok.start[1]
    raise AssertionError("no header colon after line %d" % lineno)


def lookup(site):
    """The annotation for one site, or None if the table does not cover it."""
    key = "%s::%s" % (site.rel, site.qual)
    if site.kind == "return":
        for k in (key, "%s::%s" % ("*", site.qual), site.name):
            if k in RETURNS:
                return RETURNS[k]
        return None
    for k in ("%s::%s" % (key, site.arg),
              "*::%s::%s" % (site.qual, site.arg),
              "*::*.%s::%s" % (site.name, site.arg)):
        if k in ARGS:
            return ARGS[k]
    opt = site.default == "None"
    for k in ((site.arg, opt), (site.arg, None)):
        if k in PER_NAME:
            t = PER_NAME[k]
            return (t + " | None") if opt and "None" not in t else t
    return None


def annotate(src, rel, report):
    edits = []
    missing = []
    for site in sites(src, rel, _match_any(rel, _TYPED_LIB)):
        if "%s::%s" % (site.rel, site.qual) in SKIP:
            # EXTRA rewrites this def header whole; annotating it first would
            # leave the anchor chasing text this pass had just changed.
            continue
        ann = lookup(site)
        if ann is None:
            missing.append(site)
            continue
        if site.kind == "arg":
            edits.append((site.lineno, site.col, ": " + ann))
        else:
            line, col = header_colon(src, site.lineno, 0)
            edits.append((line, col, " -> " + ann))
    if report:
        return src, missing
    lines = src.splitlines(True)
    for line, col, text in sorted(edits, reverse=True):
        s = lines[line - 1]
        lines[line - 1] = s[:col] + text + s[col:]
    out = "".join(lines)
    if edits or rel in EXTRA:
        out = add_future(out)
    if rel in IMPORTS:
        out = add_imports(out, IMPORTS[rel])
    for old, new in EXTRA.get(rel, ()):
        if out.count(old) != 1:
            raise SystemExit("%s: anchor %r matched %d times"
                             % (rel, old[:60], out.count(old)))
        out = out.replace(old, new)
    return out, missing


def add_imports(src, block):
    """Insert ``block`` after the module's last top-level import.

    The names step 05 annotates with -- ``sublime.Window``, ``Elasticsearch``,
    ``Callable`` -- are wanted by the checker and by a reader, not by the
    interpreter, so they arrive in a ``TYPE_CHECKING`` block. Placing it by
    anchor text would mean one hand-written anchor per file; placing it after
    the last import is one rule that holds for all of them.
    """
    tree = ast.parse(src)
    last = 0
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            last = node.end_lineno
    if not last:
        raise SystemExit("no top-level import to anchor the block on")
    lines = src.splitlines(True)
    lines.insert(last, block)
    return "".join(lines)


FUTURE = "from __future__ import annotations\n"


def add_future(src):
    if FUTURE in src:
        return src
    tree = ast.parse(src)
    lines = src.splitlines(True)
    body = [n for n in tree.body]
    at = 0
    if (body and isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and isinstance(body[0].value.value, str)):
        at = body[0].end_lineno
        while at < len(lines) and not lines[at].strip():
            at += 1
        lines.insert(at, FUTURE + "\n")
    else:
        while at < len(lines) and (lines[at].startswith("#")
                                   or not lines[at].strip()):
            at += 1
        lines.insert(at, FUTURE + "\n")
    return "".join(lines)



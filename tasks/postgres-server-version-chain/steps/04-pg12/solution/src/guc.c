void guc_scan(Session *s, QueryResult *r)
{
    for (int i = 0; gucs[i].name; i++) {
        int nc = r->ncols;
        Datum *row = xmalloc((size_t)nc * sizeof(Datum));
        const char *v = guc_get(s, gucs[i].name);
        int k = 0;
        row[k++] = d_text(TEXTOID, gucs[i].name);
        row[k++] = d_text(TEXTOID, v ? v : gucs[i].setting);
        row[k++] = *gucs[i].unit ? d_text(TEXTOID, gucs[i].unit) : d_null(TEXTOID);
        row[k++] = d_text(TEXTOID, gucs[i].category);
        row[k++] = d_null(TEXTOID);                       /* short_desc */
        row[k++] = d_null(TEXTOID);                       /* extra_desc */
        row[k++] = d_text(TEXTOID, guc_context(&gucs[i]));
        row[k++] = d_text(TEXTOID, gucs[i].vartype);
        row[k++] = d_text(TEXTOID, "default");            /* source */
        row[k++] = d_null(TEXTOID);                       /* min_val */
        row[k++] = d_null(TEXTOID);                       /* max_val */
        {
            static const struct { const char *nm; const char *vals[8]; int minvn; } ev[] = {
                {"password_encryption", {"md5","scram-sha-256",NULL}, 100},
                {"wal_compression", {"pglz","lz4","zstd","on","off",NULL}, 150},
                {"wal_compression", {"on","off",NULL}, 0},
                {"recovery_prefetch", {"off","on","try",NULL}, 150},
                {"default_toast_compression", {"pglz","lz4",NULL}, 140},
                {"plan_cache_mode", {"auto","force_generic_plan","force_custom_plan",NULL}, 120},
                {NULL, {NULL}, 0}
            };
            const char *const *vals = NULL;
            for (int q = 0; ev[q].nm; q++) {
                if (strcmp(ev[q].nm, gucs[i].name)) continue;
                if (ev[q].minvn && PGVC_VN < ev[q].minvn) continue;
                vals = ev[q].vals;
                break;
            }
            if (vals) {
                char *v2[8]; int nv = 0;
                while (vals[nv] && nv < 8) { v2[nv] = (char *)vals[nv]; nv++; }
                extern Datum textarr_pub(Session *s, char **v, int n);
                row[k++] = textarr_pub(s, v2, nv);
            } else row[k++] = d_null(TEXTARRAYOID);       /* enumvals */
        }
        row[k++] = d_text(TEXTOID, gucs[i].setting);      /* boot_val */
        row[k++] = d_text(TEXTOID, gucs[i].setting);      /* reset_val */
        row[k++] = d_null(TEXTOID);                       /* sourcefile */
        row[k++] = d_null(INT4OID);                       /* sourceline */
        while (k < nc) row[k++] = d_bool(false);          /* pending_restart */
        qr_addrow(r, row);
    }
}

/* SET LOCAL: remember what the session had, so the transaction end can put it
 * back.  A NULL saved value means the parameter was not set in the session. */
void guc_set_local(Session *s, const char *name, const char *val)
{
    bool seen = false;
    for (int i = 0; i < s->ngucsave; i++)
        if (!strcasecmp(s->gucsave[i].name, name)) { seen = true; break; }
    if (!seen && s->ngucsave < MAXGUC) {
        const char *cur = NULL;
        for (int i = 0; i < s->nguc; i++)
            if (!strcasecmp(s->gucs[i].name, name)) { cur = s->gucs[i].val; break; }
        s->gucsave[s->ngucsave].name = xstrdup(name);
        s->gucsave[s->ngucsave].val = cur ? xstrdup(cur) : NULL;
        s->ngucsave++;
    }
    guc_set(s, name, val);
}

void guc_end_xact(Session *s)
{
    for (int i = 0; i < s->ngucsave; i++) {
        const char *nm = s->gucsave[i].name;
        int at = -1;
        for (int k = 0; k < s->nguc; k++)
            if (!strcasecmp(s->gucs[k].name, nm)) { at = k; break; }
        if (s->gucsave[i].val) {
            if (at >= 0) { free(s->gucs[at].val); s->gucs[at].val = xstrdup(s->gucsave[i].val); }
            else if (s->nguc < MAXGUC) {
                s->gucs[s->nguc].name = xstrdup(nm);
                s->gucs[s->nguc].val = xstrdup(s->gucsave[i].val);
                s->nguc++;
            }
        } else if (at >= 0) {
            free(s->gucs[at].name); free(s->gucs[at].val);
            memmove(&s->gucs[at], &s->gucs[at+1], (size_t)(s->nguc-at-1) * sizeof(GucVal));
            s->nguc--;
        }
        free(s->gucsave[i].name); free(s->gucsave[i].val);
    }
    s->ngucsave = 0;
}

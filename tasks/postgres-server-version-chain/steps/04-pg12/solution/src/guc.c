/* Values the server itself owns rather than inheriting from the recorded table. */
static const char *server_owned(Session *s, const char *name)
{
#if PGVC_VN >= 120
    /* PostgreSQL 12 keeps default_with_oids as a no-op that only accepts
     * false, and hides it from pg_settings. */
    if (!strcasecmp(name, "default_with_oids")) return "off";
#endif
    if (!strcmp(name, "server_version")) return PGVC_VERSION_TEXT;
    if (!strcmp(name, "server_version_num")) return PGVC_VERSION_NUM;
    if (!strcmp(name, "is_superuser")) return "on";
    if (!strcmp(name, "session_authorization")) return s && s->user ? s->user : "postgres";
    return NULL;
}

static int guc_find(const char *name)
{
    for (int i = 0; gucs[i].name; i++) if (!strcasecmp(gucs[i].name, name)) return i;
    return -1;
}

const char *guc_canonical(const char *name)
{
    int i = guc_find(name);
    return i >= 0 ? gucs[i].name : name;
}

bool guc_known(const char *name) { return guc_find(name) >= 0; }

const char *guc_default(const char *name)
{
    int i = guc_find(name);
    return i >= 0 ? gucs[i].setting : NULL;
}

static char *guc_overrides[512];
static const char *guc_override_names[512];
static int n_overrides;

void guc_set_global(const char *name, const char *val)
{
    for (int i = 0; i < n_overrides; i++)
        if (!strcasecmp(guc_override_names[i], name)) { free(guc_overrides[i]); guc_overrides[i] = xstrdup(val); return; }
    if (n_overrides < 512) { guc_override_names[n_overrides] = xstrdup(name);
                             guc_overrides[n_overrides++] = xstrdup(val); }
}
static const char *guc_global(const char *name)
{
    for (int i = 0; i < n_overrides; i++)
        if (!strcasecmp(guc_override_names[i], name)) return guc_overrides[i];
    return NULL;
}

const char *guc_get(Session *s, const char *name)
{
    const char *o = server_owned(s, name);
    if (o) return o;
    if (s) for (int i = 0; i < s->nguc; i++)
        if (!strcasecmp(s->gucs[i].name, name)) return s->gucs[i].val;
    const char *g = guc_global(name);
    if (g) return g;
    int i = guc_find(name);
    return i >= 0 ? gucs[i].setting : NULL;
}


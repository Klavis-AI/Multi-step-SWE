static char *guc_to_base_unit(const char *name, const char *val);

void guc_set(Session *s, const char *name, const char *val)
{
    if (!guc_known(name)) {
        /* PostgreSQL allows custom parameters that contain a dot. */
        if (!strchr(name, '.') && !server_owned(s, name))
            ereport(s, "42704", "unrecognized configuration parameter \"%s\"", name);
    }
    /* set_config_option() refuses a parameter this session cannot change. */
    {
        int gi = guc_find(name);
        if (gi >= 0) {
            const char *ctx = guc_context(&gucs[gi]);
            if (!strcmp(ctx, "internal"))
                ereport(s, "55P02", "parameter \"%s\" cannot be changed", gucs[gi].name);
            if (!strcmp(ctx, "postmaster"))
                ereport(s, "55P02",
                        "parameter \"%s\" cannot be changed without restarting the server",
                        gucs[gi].name);
            if (!strcmp(ctx, "sighup"))
                ereport(s, "55P02", "parameter \"%s\" cannot be changed now", gucs[gi].name);
        }
    }
    if (!val) val = "";
    char *norm = guc_to_base_unit(name, val);
    if (!norm) norm = xstrdup(val);
    /* enum parameters only accept the values the release defines */
    if (!strcasecmp(name, "plan_cache_mode")) {
        for (char *q = norm; *q; q++) *q = (char)tolower((unsigned char)*q);
        if (strcmp(norm, "auto") && strcmp(norm, "force_generic_plan") &&
            strcmp(norm, "force_custom_plan")) {
            err_hint(s, "Available values: auto, force_generic_plan, force_custom_plan.");
            ereport(s, "22023", "invalid value for parameter \"plan_cache_mode\": \"%s\"", val);
        }
    }
#if PGVC_VN >= 140
    if (!strcasecmp(name, "default_toast_compression")) {
        for (char *q = norm; *q; q++) *q = (char)tolower((unsigned char)*q);
        if (strcmp(norm, "pglz") && strcmp(norm, "lz4")) {
            err_hint(s, "Available values: pglz, lz4.");
            ereport(s, "22023", "invalid value for parameter \"default_toast_compression\": \"%s\"",
                    val);
        }
    }
#endif
#if PGVC_VN >= 160
    if (!strcasecmp(name, "debug_parallel_query")) {
        for (char *q = norm; *q; q++) *q = (char)tolower((unsigned char)*q);
        if (strcmp(norm,"off") && strcmp(norm,"on") && strcmp(norm,"regress") &&
            strcmp(norm,"true") && strcmp(norm,"false") && strcmp(norm,"yes") &&
            strcmp(norm,"no") && strcmp(norm,"1") && strcmp(norm,"0")) {
            err_hint(s, "Available values: off, on, regress.");
            ereport(s, "22023", "invalid value for parameter \"debug_parallel_query\": \"%s\"", val);
        }
    }
#else
    if (!strcasecmp(name, "force_parallel_mode")) {
        for (char *q = norm; *q; q++) *q = (char)tolower((unsigned char)*q);
        if (strcmp(norm,"off") && strcmp(norm,"on") && strcmp(norm,"regress") &&
            strcmp(norm,"true") && strcmp(norm,"false") && strcmp(norm,"yes") &&
            strcmp(norm,"no") && strcmp(norm,"1") && strcmp(norm,"0")) {
            err_hint(s, "Available values: off, on, regress.");
            ereport(s, "22023", "invalid value for parameter \"force_parallel_mode\": \"%s\"", val);
        }
    }
#endif
    if (!strcasecmp(name, "default_table_access_method")) {
        if (strcmp(norm, "heap")) {
            err_detail(s, "Table access method \"%s\" does not exist.", val);
            ereport(s, "22023", "invalid value for parameter \"default_table_access_method\": \"%s\"", val);
        }
    }
#if PGVC_VN >= 120
    if (!strcasecmp(name, "default_with_oids")) {
        if (*norm && strcasecmp(norm, "off") && strcasecmp(norm, "false") &&
            strcasecmp(norm, "no") && strcmp(norm, "0"))
            ereport(s, "0A000", "tables declared WITH OIDS are not supported");
        free(norm);
        return;
    }
#endif
    if (!strcasecmp(name, "password_encryption")) {
        for (char *q = norm; *q; q++) *q = (char)tolower((unsigned char)*q);
#if PGVC_VN >= 100
        if (strcmp(norm, "md5") && strcmp(norm, "scram-sha-256")) {
            err_hint(s, "Available values: md5, scram-sha-256.");
            ereport(s, "22023", "invalid value for parameter \"password_encryption\": \"%s\"", val);
        }
#else
        if (strcmp(norm,"on") && strcmp(norm,"off") && strcmp(norm,"true") &&
            strcmp(norm,"false") && strcmp(norm,"plain") && strcmp(norm,"md5") &&
            strcmp(norm,"1") && strcmp(norm,"0") && strcmp(norm,"yes") && strcmp(norm,"no")) {
            err_hint(s, "Available values: on, off, true, false, yes, no, 1, 0, plain, md5.");
            ereport(s, "22023", "invalid value for parameter \"password_encryption\": \"%s\"", val);
        }
#endif
    }
    if (!strcmp(name, "search_path") || !strcmp(name, "DateStyle") || !strcmp(name, "datestyle")) { }
    for (int i = 0; i < s->nguc; i++)
        if (!strcasecmp(s->gucs[i].name, name)) { free(s->gucs[i].val); s->gucs[i].val = norm; return; }
    if (s->nguc < MAXGUC) { s->gucs[s->nguc].name = xstrdup(name); s->gucs[s->nguc].val = norm; s->nguc++; }
}


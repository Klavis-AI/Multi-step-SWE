/* A few parameters have a show hook in PostgreSQL that prints the raw value. */
static bool guc_raw_show(const char *name)
{
    return !strcmp(name, "tcp_keepalives_idle") ||
           !strcmp(name, "tcp_keepalives_interval") ||
           !strcmp(name, "tcp_keepalives_count");
}

/* "60s" for a parameter measured in ms becomes "60000", the way
 * PostgreSQL's convert_to_base_unit() stores it. */
static char *guc_to_base_unit(const char *name, const char *val)
{
    int i = guc_find(name);
    if (i < 0 || !val) return NULL;
    const char *unit = gucs[i].unit;
    if (!unit || !*unit) return NULL;
    if (strcmp(gucs[i].vartype, "integer") && strcmp(gucs[i].vartype, "real")) return NULL;
    char *end;
    double v = strtod(val, &end);
    if (end == val) return NULL;
    while (*end == ' ') end++;
    if (!*end) return NULL;                    /* already in the base unit */
    for (int k = 0; unit_table[k].unit; k++) {
        if (strcmp(unit_table[k].base, unit)) continue;
        if (strcmp(unit_table[k].unit, end)) continue;
        char buf[64];
        double scaled = v * unit_table[k].mult;
        if (!strcmp(gucs[i].vartype, "integer"))
            snprintf(buf, sizeof buf, "%lld", (long long)llrint(scaled));
        else
            snprintf(buf, sizeof buf, "%g", scaled);
        return xstrdup(buf);
    }
    return NULL;
}

char *guc_with_unit(const char *name, const char *vartype, const char *unit,
                    const char *val)
{
    Buf b; buf_init(&b);
    if (!unit || !*unit || !val || guc_raw_show(name)) { buf_adds(&b, val ? val : ""); return buf_steal(&b); }
    if (!strcmp(vartype, "integer")) {
        char *end;
        long long v = strtoll(val, &end, 10);
        if (end == val || *end || v <= 0) { buf_adds(&b, val); return buf_steal(&b); }
        for (int i = 0; unit_table[i].unit; i++) {
            if (strcmp(unit_table[i].base, unit)) continue;
            if (unit_table[i].mult <= 1.0 || (v % (long long)unit_table[i].mult) == 0) {
                buf_printf(&b, "%lld%s", (long long)llrint((double)v / unit_table[i].mult),
                           unit_table[i].unit);
                return buf_steal(&b);
            }
        }
        buf_adds(&b, val);
        return buf_steal(&b);
    }
    if (!strcmp(vartype, "real")) {
        char *end;
        double v = strtod(val, &end);
        if (end == val || *end || !(v > 0)) { buf_adds(&b, val); return buf_steal(&b); }
        for (int i = 0; unit_table[i].unit; i++) {
            if (strcmp(unit_table[i].base, unit)) continue;
            double r = v / unit_table[i].mult;
            if (r > 0 && fabs(r - rint(r)) < 1e-6) {
                buf_printf(&b, "%g%s", r, unit_table[i].unit);
                return buf_steal(&b);
            }
        }
        buf_adds(&b, val);
        return buf_steal(&b);
    }
    buf_adds(&b, val);
    return buf_steal(&b);
}

/* SHOW and current_setting() go through here; pg_settings.setting does not. */
char *guc_show(Session *s, const char *name)
{
    const char *v = guc_get(s, name);
    if (!v) return NULL;
    int i = guc_find(name);
    if (i < 0) return xstrdup(v);
    return guc_with_unit(gucs[i].name, gucs[i].vartype, gucs[i].unit, v);
}


CREATE TABLE q4_cie(i int);
WITH w AS NOT MATERIALIZED (INSERT INTO q4_cie VALUES (1) RETURNING i) SELECT count(*) FROM w;
WITH RECURSIVE w AS NOT MATERIALIZED (SELECT 1 n UNION ALL SELECT n+1 FROM w WHERE n < 3)
  SELECT count(*) FROM w;
WITH w AS MATERIALIZED NOT MATERIALIZED (SELECT 1) SELECT * FROM w;
WITH w AS MATERIALISED (SELECT 1) SELECT * FROM w;
SELECT i FROM q4_cie ORDER BY i;

SELECT a, b, count(*) FROM (VALUES (1,2),(1,2)) v(a,b)
  GROUP BY DISTINCT CUBE(a,b) ORDER BY a NULLS LAST, b NULLS LAST;
SELECT a, b, count(*) FROM (VALUES (1,2),(1,2)) v(a,b)
  GROUP BY DISTINCT ROLLUP(a,b), ROLLUP(a) ORDER BY a NULLS LAST, b NULLS LAST;
SELECT a, count(*) FROM (VALUES (1),(2)) v(a)
  GROUP BY DISTINCT GROUPING SETS ((a),(a),()) ORDER BY a NULLS LAST;

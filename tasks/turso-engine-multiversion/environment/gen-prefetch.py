#!/usr/bin/env python3
"""Generate one dependency-graph stand-in per step, for the image's registry cache.

    gen-prefetch.py <step-Cargo.lock> <out-dir>

The agent's environment has no general network access, so every crate a build
can reach must already be in the image's CARGO_HOME. This script turns one
step's frozen Cargo.lock into a crate whose only purpose is to make
`cargo fetch` populate that cache:

  * Cargo.toml lists every registry package the lock names as a direct,
    renamed, exactly-pinned dependency, with default features off. Because they
    are all direct, nothing in the lock is unreachable and cargo cannot
    re-resolve a version upwards; because their features are off, no crate
    drags in an optional dependency the step's own feature selection never
    turned on, so the fetched set equals the frozen set exactly.
  * Cargo.lock is the step's frozen lock with the workspace's own path members
    deleted and this stand-in put in their place, so the checksums and the
    exact versions are the ones the step really compiles.
  * src/ is a stub: no implementation, no path members, nothing of the task.

The locks these are generated from are the ones the step's own solution
payload produces. Reconstruct them with:

    for n in 01 02 ... 15; do
      git apply -p1 <solve-dir>/release-*.patch          # in release order
      cp Cargo.lock locks/$n/
    done

starting from the step-01 baseline tarball in steps/01-baseline-engine.
"""

import os
import re
import sys

STAND_IN = "prefetch-stand-in"

# Nothing in the frozen locks is left out of the cache, and one pair needs a
# word because it looks like a candidate for leaving out:
#
#   rusqlite / libsqlite3-sys -- bindings to the stock SQLite that the task's
#   own contract (spec/PROFILE.md, "The second implementation on this
#   machine") forbids /app from linking, embedding, vendoring or shelling out
#   to. They are a dev-dependency of the upstream workspace, and cargo refuses
#   to build that workspace offline while any package its lock names is
#   missing from the cache, dev-dependency or not: with them left out,
#   `cargo build --release --offline --bin limbo` in the step-01 tree fails
#   with "error: no matching package named `rusqlite` found". The reference
#   solution runs in this same container under this same network policy, so
#   leaving them out breaks the oracle at every one of the fifteen steps.
#   They are cached. See WORK_REPORT.md for the trade this makes and for the
#   check that would have to exist verifier-side to close it.
#
# The project being reimplemented is not in this set at all, and cannot be:
# every turso_*/limbo_*/sqlite3-parser package in the fifteen locks is a path
# member of the workspace, and path members are dropped by construction.
EXCLUDED = set()

HEADER_TOML = """\
# Generated by gen-prefetch.py from this step's frozen Cargo.lock.
# Not the task's code: a dependency-graph stand-in whose only purpose is
# to make `cargo fetch` populate the registry cache in the image being
# built, so a build there needs no mirror. Do not edit.

[package]
name = "{name}"
version = "0.0.0"
edition = "2021"
publish = false

# Standalone: must not be absorbed into any surrounding workspace.
[workspace]
"""

HEADER_LOCK = """\
# Generated by gen-prefetch.py. Do not edit.
# The step's frozen Cargo.lock with its workspace members replaced by
# the stand-in package, so `cargo fetch` resolves nothing and yanked
# releases the step really compiles stay reachable.
"""


def parse_lock(text):
    """Split a cargo lock into package blocks, keeping each block's text."""
    packages = []
    for block in re.split(r"(?m)^\[\[package\]\]$", text)[1:]:
        name = re.search(r'(?m)^name = "(.*)"$', block).group(1)
        version = re.search(r'(?m)^version = "(.*)"$', block).group(1)
        source = re.search(r'(?m)^source = "(.*)"$', block)
        packages.append({
            "name": name,
            "version": version,
            "source": source.group(1) if source else None,
            "text": block.strip("\n"),
        })
    return packages


def dep_key(dep):
    """A lock dependency string 'name' or 'name version' -> (name, version|None)."""
    parts = dep.split(" ", 1)
    return parts[0], (parts[1] if len(parts) > 1 else None)


def dep_lines(block):
    body = re.search(r"(?ms)^dependencies = \[\n(.*?)^\]$", block)
    if not body:
        return []
    return [d.strip().rstrip(",").strip('"') for d in body.group(1).splitlines() if d.strip()]


def rename_key(name, version):
    return re.sub(r"[^0-9A-Za-z]+", "_", f"{name}_{version}").strip("_")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip().splitlines()[2].strip())
    lock_path, out_dir = sys.argv[1], sys.argv[2]

    packages = parse_lock(open(lock_path).read())
    src = lambda p: p["source"] or ""  # noqa: E731
    local = [p for p in packages if p["source"] is None]
    registry = [p for p in packages if src(p).startswith("registry+")]
    git = [p for p in packages if src(p).startswith("git+")]
    other = [p for p in packages
             if p["source"] and not src(p).startswith(("registry+", "git+"))]
    if other:
        sys.exit(f"unsupported sources: {[p['source'] for p in other]}")

    dropped = [p for p in registry if p["name"] in EXCLUDED]
    registry = [p for p in registry if p["name"] not in EXCLUDED]
    kept = registry + git

    # Nothing kept may depend on something dropped: a dangling reference would
    # make the lock unresolvable rather than merely incomplete.
    dropped_names = {p["name"] for p in dropped} | {p["name"] for p in local}
    for p in kept:
        for dep in p["deps"] if "deps" in p else dep_lines(p["text"]):
            name, _ = dep_key(dep)
            if name in dropped_names:
                sys.exit(f"{p['name']} still depends on dropped {name}")

    # Two crates, two versions in one lock -> the shorter lock spelling is
    # ambiguous in the stand-in's dependency list, so disambiguate every edge.
    counts = {}
    for p in kept:
        counts[p["name"]] = counts.get(p["name"], 0) + 1

    deps = []
    for p in sorted(kept, key=lambda p: (p["name"], p["version"])):
        if counts[p["name"]] > 1:
            deps.append(f'"{p["name"]} {p["version"]}"')
        else:
            deps.append(f'"{p["name"]}"')

    os.makedirs(os.path.join(out_dir, "src"), exist_ok=True)

    # --- Cargo.toml ---------------------------------------------------------
    lines = [HEADER_TOML.format(name=STAND_IN), "[dependencies]"]
    if dropped:
        lines.append("# Registry packages deliberately not cached: "
                     + ", ".join(sorted(f"{p['name']} {p['version']}" for p in dropped)))
    for p in sorted(kept, key=lambda p: rename_key(p["name"], p["version"])):
        key = rename_key(p["name"], p["version"])
        if p["source"].startswith("git+"):
            # git+https://host/path.git?rev=<asked>#<resolved>
            url_part, _, resolved = p["source"][len("git+"):].partition("#")
            url, _, query = url_part.partition("?")
            rev = resolved or query.split("rev=")[-1].split("&")[0]
            lines.append(f'{key} = {{ package = "{p["name"]}", '
                         f'git = "{url}", rev = "{rev}" }}')
        else:
            # default-features = false keeps the resolve inside the frozen set:
            # every package below is already a direct dependency, so nothing
            # the step compiles is missed, and no feature the step never
            # enabled drags in a crate the step never used.
            lines.append(f'{key} = {{ package = "{p["name"]}", '
                         f'version = "={p["version"]}", default-features = false }}')
    open(os.path.join(out_dir, "Cargo.toml"), "w").write("\n".join(lines) + "\n")

    # --- Cargo.lock ---------------------------------------------------------
    lock = [HEADER_LOCK, "version = 4", "", "[[package]]",
            f'name = "{STAND_IN}"', 'version = "0.0.0"', "dependencies = ["]
    lock += [f" {d}," for d in deps]
    lock += ["]", ""]
    for p in sorted(kept, key=lambda p: (p["name"], p["version"])):
        lock += ["[[package]]", p["text"], ""]
    open(os.path.join(out_dir, "Cargo.lock"), "w").write("\n".join(lock))

    open(os.path.join(out_dir, "src", "lib.rs"), "w").write(
        "// Intentionally empty. See Cargo.toml.\n")

    print(f"{out_dir}: {len(kept)} packages cached "
          f"({len(registry)} registry, {len(git)} git), "
          f"{len(dropped)} dropped, {len(local)} path members left out")


if __name__ == "__main__":
    main()

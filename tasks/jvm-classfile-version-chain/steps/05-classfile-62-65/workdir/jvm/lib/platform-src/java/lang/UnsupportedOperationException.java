package java.lang;
public class UnsupportedOperationException extends RuntimeException {
    public UnsupportedOperationException() { super(); }
    public UnsupportedOperationException(String s) { super(s); }
    public UnsupportedOperationException(String s, Throwable c) { super(s, c); }
    public UnsupportedOperationException(Throwable c) { super(c); }
}

package java.lang;
public class ReflectiveOperationException extends Exception {
    public ReflectiveOperationException() { super(); }
    public ReflectiveOperationException(String s) { super(s); }
    public ReflectiveOperationException(String s, Throwable c) { super(s, c); }
    public ReflectiveOperationException(Throwable c) { super(c); }
}

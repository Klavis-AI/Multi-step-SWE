package java.lang.invoke;
public class LambdaConversionException extends Exception {
    public LambdaConversionException() { super(); }
    public LambdaConversionException(String message) { super(message); }
    public LambdaConversionException(String message, Throwable cause) { super(message, cause); }
    public LambdaConversionException(Throwable cause) { super(cause); }
}

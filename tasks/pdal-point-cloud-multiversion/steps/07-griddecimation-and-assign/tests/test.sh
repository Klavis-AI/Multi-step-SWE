#!/usr/bin/env bash

# --- verifier/step binding check -------------------------------------------
# /etc/harbor-step-id names the image; the literal below names this tests/ tree.
# They disagree only when the build context came from another step's cache
# entry, in which case every check below would grade the wrong milestone.
# Reported, not crashed: a non-zero exit makes Harbor skip the remaining steps
# and buries the fault under a second symptom.
__hb_want=07
__hb_got=$(cat /etc/harbor-step-id 2>/dev/null) || __hb_got=MISSING
if [ "$__hb_got" != "$__hb_want" ]; then
    __hb_msg="VERIFIER/STEP MISMATCH: image is step ${__hb_got}, /tests tree is step ${__hb_want}."
    printf '%s\n' "$__hb_msg" >&2
    mkdir -p /logs/verifier 2>/dev/null
    printf '%s\n' "$__hb_msg" > /logs/verifier/step-mismatch.log
    printf '{"reward":0,"verifier_error":"step_mismatch","image_step":"%s","tests_step":"%s"}\n' \
        "$__hb_got" "$__hb_want" > /logs/verifier/reward.json
    exit 0
fi
unset __hb_want __hb_got __hb_msg
# --- end binding check ------------------------------------------------------
#
# Verifier entry point for step 07 (PDAL 2.7.1).
#
# One copy per step, generated by
# misc/pdal-point-cloud-multiversion/build-package.sh from
# misc/pdal-point-cloud-multiversion/template/test.sh.tmpl. What differs
# between steps is assets/groups.txt, assets/cases/, assets/fixtures/ and the
# STEP/RELEASE values substituted here.
#
# Runs in this step's verifier container on a fresh copy of /app. Nothing
# written here reaches the next step; only /logs/verifier is read back.
#
#   reward = gate x score
#
#     gate  in {0,1}   every GATE group passes completely, or the step is 0.
#                      Proof of life (the candidate configures, builds and the
#                      `pdal` program runs) plus one deterministic end-to-end
#                      path through each milestone this step inherits. Earns
#                      no credit of its own.
#     score in [0,1]   weight-sum over the SCORED groups only, each group
#                      contributing weight x (cases passed / cases declared).
#                      The scored weights sum to 1.0 among themselves.
#
# A no-op candidate therefore scores exactly 0: it preserves the inherited
# behaviour (gate = 1) and implements no new capability (score = 0).
set -u
source /tests/helpers.sh

STEP=07
RELEASE=2.7.1

log_dir=/tmp/pdal-verifier
build_dir=/tmp/pdal-build
stage=/tmp/pdal-stage
rm -rf -- "$log_dir" "$build_dir" "$stage"
mkdir -p "$log_dir" "$log_dir/case-logs" "$build_dir" "$stage"

app=/app
groups_file=/tests/assets/groups.txt

# Budgets. Every number below is reachable in the worst case and the sum is
# what [steps.verifier] timeout_sec in task.toml must cover; see the note
# there. CONFIGURE_MAX + BUILD_MAX + CASE_MAX x (declared cases) + slack.
CONFIGURE_MAX=600
BUILD_MAX=3000
CASE_MAX=60

harden_reward_dir

note() { printf '%s\n' "$*" >> "$log_dir/harness.log"; }

# ---------------------------------------------------------------------------
# Group table. Every declared group is reported exactly once, as a pass, a
# partial or a failure - never skipped. The exit trap closes out any group the
# run never reached, so a verifier that dies half way through still reports a
# complete scorecard rather than a missing reward.json.
#
# groups.txt columns:  <name> <gate|scored> <weight> <declared-case-count>
# ---------------------------------------------------------------------------
declare -a GROUP_NAMES=()
declare -A GROUP_KIND=() GROUP_WEIGHT=() GROUP_WANT=()
while read -r gname gkind gweight gcount; do
    case "$gname" in ''|\#*) continue ;; esac
    GROUP_NAMES+=("$gname")
    GROUP_KIND["$gname"]=$gkind
    GROUP_WEIGHT["$gname"]=$gweight
    GROUP_WANT["$gname"]=$gcount
done < "$groups_file"

gate_result=1
gate_reason=""
finished=0
recorded=","
group_json=""
newcap_w=0; newcap_earned=0
declare -A GROUP_PASSED=()

# record <group> <passed-cases> <detail>
record() {
    local name="$1" p="$2" detail="${3:-}"
    case "$recorded" in *,"$name",*) return ;; esac
    recorded="${recorded}${name},"
    local want=${GROUP_WANT[$name]}
    GROUP_PASSED["$name"]=$p
    local kind=${GROUP_KIND[$name]}
    local frac
    frac=$(awk -v n="$p" -v d="$want" 'BEGIN { if (d <= 0) printf "0.000000"; else printf "%.6f", n / d }')
    if [ "$kind" = gate ]; then
        if [ "$p" -ne "$want" ]; then
            gate_result=0
            [ -n "$gate_reason" ] && gate_reason="$gate_reason; "
            gate_reason="${gate_reason}${name} (${p}/${want}: ${detail})"
        fi
    else
        newcap_w=$(awk -v a="$newcap_w" -v b="${GROUP_WEIGHT[$name]}" 'BEGIN { printf "%.6f", a + b }')
        newcap_earned=$(awk -v a="$newcap_earned" -v w="${GROUP_WEIGHT[$name]}" -v f="$frac" \
            'BEGIN { printf "%.6f", a + w * f }')
    fi
    group_json="${group_json}${group_json:+,}\"$name\":{\"kind\":\"$kind\",\"weight\":${GROUP_WEIGHT[$name]},\"passed\":$p,\"declared\":$want,\"detail\":\"$(printf '%s' "$detail" | sed 's/[\\"]/ /g')\"}"
    printf '%s %s %s %s/%s %s\n' \
        "$([ "$p" -eq "$want" ] && echo PASS || echo FAIL)" "$kind" "$name" "$p" "$want" "$detail" \
        >> "$log_dir/groups.txt"
}

write_details() {
    local score="$1" reward="$2"
    printf '{"step":"%s","release":"%s","gate":%s,"gate_reason":"%s","score":%s,"reward":%s,"declared_groups":%s,"scored_weight_total":%s,"groups":{%s}}\n' \
        "$STEP" "$RELEASE" "$gate_result" "$(printf '%s' "$gate_reason" | sed 's/[\\"]/ /g')" \
        "$score" "$reward" "${#GROUP_NAMES[@]}" "$newcap_w" "$group_json" \
        > /logs/verifier/reward_details.json
}

finish() {
    local score reward
    finished=1
    cp "$log_dir/groups.txt" /logs/verifier/groups.txt 2>/dev/null || true
    mkdir -p /logs/verifier/failed
    if [ -f "$log_dir/groups.txt" ]; then
        while read -r status _kind name _rest; do
            [ "$status" = FAIL ] || continue
            [ -f "$log_dir/case-logs/$name.log" ] && \
                tail -c 20000 "$log_dir/case-logs/$name.log" > "/logs/verifier/failed/$name.log"
        done < "$log_dir/groups.txt"
    fi
    for b in build configure assets harness; do
        [ -s "$log_dir/$b.log" ] && tail -c 20000 "$log_dir/$b.log" > "/logs/verifier/$b.log"
    done
    # Passing groups' case logs too, capped: a reviewer checking that a case
    # asserted what it claims needs the per-case lines, not just the failures.
    mkdir -p /logs/verifier/cases
    for f in "$log_dir"/case-logs/*.log; do
        [ -f "$f" ] && tail -c 20000 "$f" > "/logs/verifier/cases/$(basename "$f")"
    done
    # score is the weight-sum over the scored groups; the weights in groups.txt
    # sum to 1.0, so no renormalisation is applied - a groups.txt whose scored
    # weights do not sum to 1.0 is an authoring defect the integrity check
    # below refuses before any case runs.
    score=$(awk -v v="$newcap_earned" 'BEGIN { if (v < 0) v = 0; if (v > 1) v = 1; printf "%.6f", v }')
    reward=$(awk -v g="$gate_result" -v s="$score" 'BEGIN { printf "%.6f", g * s }')
    write_details "$score" "$reward"
    report "$reward"
}

fail_everything() {
    : > "$log_dir/groups.txt"
    recorded=","; group_json=""; newcap_w=0; newcap_earned=0
    gate_result=1; gate_reason=""
    local g
    for g in "${GROUP_NAMES[@]}"; do record "$g" 0 "$1"; done
    finish
}

on_exit() {
    [ "$finished" -eq 1 ] && return
    local g
    for g in "${GROUP_NAMES[@]}"; do record "$g" 0 "verifier ended before this group ran"; done
    finish
}
trap on_exit EXIT

# ---------------------------------------------------------------------------
# Asset integrity. The corpus is verifier-owned and pinned; a corpus that does
# not match its manifest is an authoring fault, not a candidate fault, so every
# group is failed with that reason rather than silently scoring the candidate
# against a corpus nobody checked.
# ---------------------------------------------------------------------------
if [ "${#GROUP_NAMES[@]}" -eq 0 ]; then
    note "groups.txt declared no groups"
    mkdir -p /logs/verifier
    printf '{"reward":0,"verifier_error":"empty_groups_txt"}\n' > /logs/verifier/reward.json
    exit 0
fi

( cd /tests/assets && sha256sum -c --quiet SHA256SUMS ) >> "$log_dir/assets.log" 2>&1 \
    || fail_everything "verifier corpus failed its integrity check"

# Declared case counts must match the corpus on disk, and the scored weights
# must sum to 1.0.
python3 /tests/driver.py --self-check --groups "$groups_file" --cases /tests/assets/cases \
    >> "$log_dir/assets.log" 2>&1 \
    || fail_everything "verifier corpus does not match groups.txt"

# ---------------------------------------------------------------------------
# Build the candidate. Out-of-tree, with the verifier's own flags, as an
# unprivileged user: nothing in /app is trusted and nothing the candidate ships
# chooses how it is compiled.
# ---------------------------------------------------------------------------
give_app_to_unprivileged
# The driver runs unprivileged and writes one result file per group; it needs
# a directory it owns. The rest of $log_dir stays root's.
results_dir="$log_dir/results"
mkdir -p "$results_dir"
chown -R "$SCORE_UID:$SCORE_GID" "$build_dir" "$stage" "$results_dir" 2>/dev/null || true

build_ok=1
if [ ! -f "$app/CMakeLists.txt" ]; then
    note "no CMakeLists.txt in /app"
    echo "no CMakeLists.txt at the top of /app" >> "$log_dir/configure.log"
else
    run_unprivileged timeout "$CONFIGURE_MAX" cmake -S "$app" -B "$build_dir" -G Ninja \
        -DCMAKE_BUILD_TYPE=Release -DWITH_TESTS=OFF -DBUILD_PLUGIN_HDF=OFF -DBUILD_PLUGIN_NITF=OFF -DBUILD_PLUGIN_PGPOINTCLOUD=OFF -DBUILD_PLUGIN_TILEDB=OFF -DBUILD_PLUGIN_DRACO=OFF -DBUILD_PLUGIN_E57=OFF -DBUILD_PLUGIN_ICEBRIDGE=OFF -DBUILD_PLUGIN_TRAJECTORY=OFF >> "$log_dir/configure.log" 2>&1
    if [ $? -ne 0 ]; then
        note "cmake configure failed"
    else
        run_unprivileged timeout "$BUILD_MAX" cmake --build "$build_dir" -j "$(nproc)" \
            >> "$log_dir/build.log" 2>&1
        if [ $? -ne 0 ]; then
            note "build failed"
        elif [ ! -x "$build_dir/bin/pdal" ]; then
            note "build produced no bin/pdal"
            echo "no executable at bin/pdal after a successful build" >> "$log_dir/build.log"
        else
            build_ok=0
        fi
    fi
fi

PDAL_BIN="$build_dir/bin/pdal"
export PDAL_DRIVER_PATH="$build_dir/lib"
export LD_LIBRARY_PATH="$build_dir/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

# ---------------------------------------------------------------------------
# Run every group. Every group runs even after another fails.
# ---------------------------------------------------------------------------
run_group() {
    local name="$1" want=${GROUP_WANT[$1]}
    local logf="$log_dir/case-logs/$name.log"
    : > "$logf"
    if [ "$build_ok" -ne 0 ]; then
        echo "candidate did not configure or build; see configure.log and build.log" >> "$logf"
        record "$name" 0 "build-failed"
        return
    fi
    local budget=$((CASE_MAX * want + 60))
    run_unprivileged timeout "$budget" env \
        PDAL_BIN="$PDAL_BIN" \
        PDAL_DRIVER_PATH="$PDAL_DRIVER_PATH" \
        LD_LIBRARY_PATH="$LD_LIBRARY_PATH" \
        PATH="/usr/local/bin:/usr/bin:/bin" \
        python3 /tests/driver.py --run \
            --group "$name" \
            --cases /tests/assets/cases \
            --fixtures /tests/assets/fixtures \
            --stage "$stage/$name" \
            --case-timeout "$CASE_MAX" \
            --report "$results_dir/$name.result.json" >> "$logf" 2>&1
    local rc=$?
    local p executed
    p=$(python3 -c 'import json,sys
try:
    d=json.load(open(sys.argv[1]))
    print(d.get("passed",0), d.get("executed",0))
except Exception:
    print(0,0)' "$results_dir/$name.result.json" 2>/dev/null)
    executed=${p#* }; p=${p%% *}
    printf 'group %s: rc=%s executed=%s declared=%s passed=%s\n' \
        "$name" "$rc" "$executed" "$want" "$p" >> "$logf"
    if [ "$executed" -ne "$want" ]; then
        # An executed count that disagrees with the declaration is never a
        # pass: a filter that matched nothing, a driver that died half way, or
        # a corpus mismatch all land here and are scored on the declared
        # denominator.
        record "$name" "$p" "executed=$executed/$want rc=$rc"
    else
        record "$name" "$p" "executed=$executed rc=$rc"
    fi
}

for g in "${GROUP_NAMES[@]}"; do run_group "$g"; done

finish

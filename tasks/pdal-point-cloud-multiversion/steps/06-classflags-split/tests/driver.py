def stage_case(case, case_dir, fixtures):
    os.makedirs(case_dir, exist_ok=True)
    for name, src in (case.get("files") or {}).items():
        dest = os.path.join(case_dir, name)
        parent = os.path.dirname(dest)
        if parent:
            os.makedirs(parent, exist_ok=True)
        if "text" in src:
            with open(dest, "w") as fh:
                fh.write(src["text"])
        elif "fixture" in src:
            shutil.copyfile(os.path.join(fixtures, src["fixture"]), dest)
        else:
            raise ValueError("file %r declares neither text nor fixture" % name)


def run_case(case, case_dir, pdal_bin, timeout):
    """Run every invocation. Returns a list of {rc, stdout, stderr, timeout}."""
    results = []
    env = dict(os.environ)
    env.setdefault("TZ", "UTC")
    env["LC_ALL"] = "C"
    for inv in case.get("run") or []:
        argv = [pdal_bin] + [str(a) for a in inv["argv"]]
        try:
            proc = subprocess.run(
                argv, cwd=case_dir, input=inv.get("stdin", ""), env=env,
                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                timeout=timeout, text=True, errors="replace")
            res = {"rc": proc.returncode, "stdout": proc.stdout,
                   "stderr": proc.stderr, "timeout": False}
        except subprocess.TimeoutExpired:
            res = {"rc": -1, "stdout": "", "stderr": "timed out after %ss" % timeout,
                   "timeout": True}
        except OSError as exc:
            res = {"rc": -1, "stdout": "", "stderr": "could not execute: %s" % exc,
                   "timeout": False}
        if inv.get("stdout_to"):
            with open(os.path.join(case_dir, inv["stdout_to"]), "w") as fh:
                fh.write(res["stdout"])
        results.append(res)
    return results


def apply_checks(case, case_dir, runs):
    failures = []
    for spec in case.get("checks") or []:
        kind = spec.get("kind")
        if kind not in CHECK_KINDS:
            failures.append("unknown check kind %r" % kind)
            continue
        idx = spec.get("run", 0)
        if kind in ("exit", "stdout_regex", "stderr_regex", "stdout_json",
                    "stdout_lines"):
            if idx >= len(runs):
                failures.append("%s: no invocation %d" % (kind, idx))
                continue
            run = runs[idx]
        try:
            if kind == "exit":
                if run["timeout"]:
                    failures.append("exit[%d]: the invocation timed out" % idx)
                    continue
                if "nonzero" in spec and spec["nonzero"]:
                    if run["rc"] == 0:
                        failures.append("exit[%d]: got 0, expected a non-zero status" % idx)
                else:
                    failures += cmp_value(run["rc"], spec, "exit[%d]" % idx)
            elif kind == "stdout_regex":
                failures += cmp_value(run["stdout"], {"regex": spec["regex"]},
                                      "stdout[%d]" % idx)
            elif kind == "stderr_regex":
                combined = run["stderr"] + run["stdout"]
                if spec.get("absent"):
                    if re.search(spec["regex"], combined):
                        failures.append("stderr[%d]: matched /%s/ and should not"
                                        % (idx, spec["regex"]))
                else:
                    failures += cmp_value(combined, {"regex": spec["regex"]},
                                          "stderr[%d]" % idx)
            elif kind == "stdout_lines":
                got = [ln for ln in run["stdout"].splitlines() if ln.strip()]
                failures += cmp_value(got, spec, "stdout[%d] lines" % idx)
            elif kind in ("stdout_json", "file_json"):
                if kind == "stdout_json":
                    raw, where = run["stdout"], "stdout[%d]" % idx
                else:
                    p = os.path.join(case_dir, spec["file"])
                    where = spec["file"]
                    if not os.path.exists(p):
                        failures.append("file_json: %s does not exist" % spec["file"])
                        continue
                    with open(p) as fh:
                        raw = fh.read()
                try:
                    doc = json.loads(raw)
                except ValueError as exc:
                    failures.append("%s: not valid JSON (%s)" % (where, exc))
                    continue
                path = spec.get("path", [])
                found, value = jget(doc, path)
                if spec.get("absent"):
                    if found:
                        failures.append("%s: %r is present and should not be"
                                        % (where, path))
                    continue
                if not found:
                    failures.append("%s: no such path %r" % (where, path))
                    continue
                if spec.get("exists") and not any(
                        k in spec for k in ("equals", "approx", "regex", "in",
                                            "contains", "length", "type", "min",
                                            "max", "not_equals")):
                    continue
                failures += cmp_value(value, spec, "%s %r" % (where, path))
            elif kind == "file_exists":
                if not os.path.exists(os.path.join(case_dir, spec["file"])):
                    failures.append("file_exists: %s was not produced" % spec["file"])
            elif kind == "file_absent":
                if os.path.exists(os.path.join(case_dir, spec["file"])):
                    failures.append("file_absent: %s was produced and should not be"
                                    % spec["file"])
            elif kind == "file_text_regex":
                p = os.path.join(case_dir, spec["file"])
                if not os.path.exists(p):
                    failures.append("file_text_regex: %s does not exist" % spec["file"])
                    continue
                with open(p, errors="replace") as fh:
                    text = fh.read()
                if spec.get("absent"):
                    if re.search(spec["regex"], text):
                        failures.append("file_text_regex: %s matched /%s/ and should not"
                                        % (spec["file"], spec["regex"]))
                else:
                    failures += cmp_value(text, {"regex": spec["regex"]},
                                          spec["file"])
            elif kind == "las":
                failures += check_las(case_dir, spec)
            elif kind == "las_compare":
                failures += check_las_compare(case_dir, spec)
            elif kind == "copc":
                failures += check_copc(case_dir, spec)
        except Exception as exc:  # noqa: BLE001 - one bad check never kills the group
            failures.append("%s: check raised %s: %s" % (kind, type(exc).__name__, exc))
    return failures


def load_groups(path):
    groups = []
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            name, kind, weight, count = line.split()
            groups.append((name, kind, float(weight), int(count)))
    return groups


def case_files(cases_dir, group):
    d = os.path.join(cases_dir, group)
    if not os.path.isdir(d):
        return []
    return sorted(os.path.join(d, f) for f in os.listdir(d)
                  if f.endswith(".case.json"))


def self_check(groups_path, cases_dir):
    groups = load_groups(groups_path)
    problems = []
    if not groups:
        problems.append("groups.txt declares no groups")
    names = [g[0] for g in groups]
    if len(set(names)) != len(names):
        problems.append("groups.txt repeats a group name")
    scored = [g for g in groups if g[1] == "scored"]
    gate = [g for g in groups if g[1] == "gate"]
    for g in groups:
        if g[1] not in ("gate", "scored"):
            problems.append("%s: unknown kind %r" % (g[0], g[1]))
    if not gate:
        problems.append("no gate group is declared")
    if not scored:
        problems.append("no scored group is declared")
    total_w = sum(g[2] for g in scored)
    if scored and abs(total_w - 1.0) > 1e-6:
        problems.append("scored weights sum to %.6f, expected 1.0" % total_w)
    for g in groups:
        if g[1] == "gate" and g[2] != 0:
            problems.append("%s: a gate group must carry weight 0" % g[0])
        if g[1] == "scored" and g[2] <= 0:
            problems.append("%s: a scored group must carry a positive weight" % g[0])
    seen_dirs = set()
    for name, _kind, _w, count in groups:
        files = case_files(cases_dir, name)
        seen_dirs.add(name)
        if len(files) != count:
            problems.append("%s: %d case files on disk, groups.txt declares %d"
                            % (name, len(files), count))
        for f in files:
            try:
                case = json.load(open(f))
            except ValueError as exc:
                problems.append("%s: %s is not valid JSON (%s)"
                                % (name, os.path.basename(f), exc))
                continue
            if not case.get("run"):
                problems.append("%s: %s declares no invocation"
                                % (name, os.path.basename(f)))
            if not case.get("checks"):
                problems.append("%s: %s declares no check"
                                % (name, os.path.basename(f)))
            for spec in case.get("checks") or []:
                if spec.get("kind") not in CHECK_KINDS:
                    problems.append("%s: %s uses unknown check kind %r"
                                    % (name, os.path.basename(f), spec.get("kind")))
    if os.path.isdir(cases_dir):
        for entry in sorted(os.listdir(cases_dir)):
            if os.path.isdir(os.path.join(cases_dir, entry)) and entry not in seen_dirs:
                problems.append("cases/%s is not declared in groups.txt" % entry)
    for p in problems:
        print("self-check: %s" % p)
    if problems:
        return 1
    print("self-check: %d groups, %d cases, scored weight %.6f"
          % (len(groups), sum(g[3] for g in groups), total_w))
    return 0


def run_group(group, cases_dir, fixtures, stage, timeout, report_path):
    files = case_files(cases_dir, group)
    pdal_bin = os.environ.get("PDAL_BIN", "pdal")
    result = {"group": group, "declared": len(files), "executed": 0,
              "passed": 0, "cases": []}
    for f in files:
        cid = os.path.basename(f)[:-len(".case.json")]
        case_dir = os.path.join(stage, cid)
        entry = {"id": cid, "ok": False, "failures": []}
        result["executed"] += 1
        try:
            case = json.load(open(f))
            shutil.rmtree(case_dir, ignore_errors=True)
            stage_case(case, case_dir, fixtures)
            runs = run_case(case, case_dir, pdal_bin, timeout)
            entry["failures"] = apply_checks(case, case_dir, runs)
            entry["ok"] = not entry["failures"]
            entry["rcs"] = [r["rc"] for r in runs]
            if not entry["ok"]:
                tails = []
                for i, r in enumerate(runs):
                    tails.append("  [%d] rc=%s stderr: %s"
                                 % (i, r["rc"], (r["stderr"] or "").strip()[-600:]))
                entry["transcript"] = "\n".join(tails)
        except Exception:  # noqa: BLE001 - a broken case never kills the group
            entry["failures"] = ["driver error: " + traceback.format_exc(limit=3)]
        if entry["ok"]:
            result["passed"] += 1
        result["cases"].append(entry)
        status = "ok" if entry["ok"] else "FAIL"
        print("%-5s %s/%s" % (status, group, cid))
        if not entry["ok"]:
            for fail in entry["failures"][:12]:
                print("      %s" % fail.replace("\n", "\n      "))
            if entry.get("transcript"):
                print(entry["transcript"])
        sys.stdout.flush()
    if report_path:
        with open(report_path, "w") as fh:
            json.dump(result, fh)
    print("group %s: %d/%d cases passed (executed %d)"
          % (group, result["passed"], result["declared"], result["executed"]))
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-check", action="store_true")
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--groups")
    ap.add_argument("--cases", required=True)
    ap.add_argument("--fixtures")
    ap.add_argument("--group")
    ap.add_argument("--stage")
    ap.add_argument("--case-timeout", type=int, default=60)
    ap.add_argument("--report")
    args = ap.parse_args()
    if args.self_check:
        return self_check(args.groups, args.cases)
    if args.run:
        os.makedirs(args.stage, exist_ok=True)
        return run_group(args.group, args.cases, args.fixtures, args.stage,
                         args.case_timeout, args.report)
    ap.error("one of --self-check or --run is required")
    return 2


if __name__ == "__main__":
    sys.exit(main())

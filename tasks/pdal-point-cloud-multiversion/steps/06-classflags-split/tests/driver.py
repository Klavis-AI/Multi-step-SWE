#!/usr/bin/env python3
"""Verifier-owned case driver for the pdal-point-cloud-multiversion task.

One copy per step, generated by
misc/pdal-point-cloud-multiversion/build-package.sh. It is identical in every
step; only assets/groups.txt, assets/cases/ and assets/fixtures/ differ.

The driver never imports, links or trusts candidate code. It runs the
candidate's `pdal` program as a subprocess and inspects what that process
wrote: its exit status, its stdout/stderr, the JSON it emitted and the point
cloud files it produced. Written LAS/LAZ/COPC files are read back with `laspy`
(pinned into the verifier image), never with the candidate's own binary and
never by whole-file byte comparison -- a LAS header carries the creation
day-of-year and a generating-software string, so byte equality is not a
deterministic property.

Case format (assets/cases/<group>/<id>.case.json):

  {
    "doc":   "free text: where the asserted behaviour is documented",
    "files": {"pipeline.json": {"text": "..."},
              "in.las":        {"fixture": "las/utm17.las"}},
    "run":   [{"argv": ["pipeline", "pipeline.json"], "stdin": "..."}],
    "checks": [{"kind": "exit", "run": 0, "equals": 0}, ...]
  }

Every path into JSON is a LIST of keys/indices, never a dotted string, because
PDAL's own metadata keys contain dots ("readers.las").
"""

import argparse
import json
import math
import os
import re
import shutil
import subprocess
import sys
import traceback

CHECK_KINDS = {
    "exit", "stdout_regex", "stderr_regex", "stdout_json", "file_json",
    "file_exists", "file_absent", "file_text_regex", "las", "las_compare",
    "stdout_lines", "copc",
}


# --------------------------------------------------------------------------
# JSON path helpers
# --------------------------------------------------------------------------
def jget(doc, path):
    """Walk `path` (list of str keys / int indices). Returns (found, value)."""
    cur = doc
    for key in path:
        if isinstance(key, int):
            if not isinstance(cur, list) or key >= len(cur) or key < -len(cur):
                return False, None
            cur = cur[key]
        else:
            if isinstance(cur, list):
                # Allow a numeric string index into a list.
                try:
                    idx = int(key)
                except ValueError:
                    return False, None
                if idx >= len(cur) or idx < -len(cur):
                    return False, None
                cur = cur[idx]
                continue
            if not isinstance(cur, dict) or key not in cur:
                return False, None
            cur = cur[key]
    return True, cur


def approx(a, b, tol):
    try:
        if a is None or b is None:
            return False
        return abs(float(a) - float(b)) <= tol
    except (TypeError, ValueError):
        return False


def cmp_value(got, spec, where):
    """Apply the comparison operators present in `spec` to `got`.

    Returns a list of failure strings (empty when every operator held).
    """
    out = []
    if "equals" in spec:
        if got != spec["equals"]:
            out.append("%s: got %r, expected %r" % (where, got, spec["equals"]))
    if "not_equals" in spec:
        if got == spec["not_equals"]:
            out.append("%s: got %r, expected anything else" % (where, got))
    if "approx" in spec:
        tol = spec.get("tol", 1e-6)
        if not approx(got, spec["approx"], tol):
            out.append("%s: got %r, expected %r +/- %g" % (where, got, spec["approx"], tol))
    if "min" in spec:
        try:
            if float(got) < float(spec["min"]):
                out.append("%s: got %r, expected >= %r" % (where, got, spec["min"]))
        except (TypeError, ValueError):
            out.append("%s: got %r, which is not a number" % (where, got))
    if "max" in spec:
        try:
            if float(got) > float(spec["max"]):
                out.append("%s: got %r, expected <= %r" % (where, got, spec["max"]))
        except (TypeError, ValueError):
            out.append("%s: got %r, which is not a number" % (where, got))
    if "regex" in spec:
        if got is None or not re.search(spec["regex"], str(got)):
            out.append("%s: got %r, expected to match /%s/" % (where, got, spec["regex"]))
    if "in" in spec:
        if got not in spec["in"]:
            out.append("%s: got %r, expected one of %r" % (where, got, spec["in"]))
    if "contains" in spec:
        try:
            if spec["contains"] not in got:
                out.append("%s: got %r, expected to contain %r" % (where, got, spec["contains"]))
        except TypeError:
            out.append("%s: got %r, which cannot contain %r" % (where, got, spec["contains"]))
    if "length" in spec:
        try:
            if len(got) != spec["length"]:
                out.append("%s: got length %d, expected %d" % (where, len(got), spec["length"]))
        except TypeError:
            out.append("%s: got %r, which has no length" % (where, got))
    if "type" in spec:
        want = {"str": str, "int": int, "float": float, "list": list,
                "dict": dict, "bool": bool}[spec["type"]]
        if not isinstance(got, want):
            out.append("%s: got %r of type %s, expected %s"
                       % (where, got, type(got).__name__, spec["type"]))
    return out


# --------------------------------------------------------------------------
# LAS/LAZ/COPC read-back, via laspy
# --------------------------------------------------------------------------
def read_las(path):
    import laspy
    return laspy.read(path)


def las_field(las, field):
    """Documented, deterministic header/point observations only."""
    hdr = las.header
    if field == "version":
        return "%d.%d" % (hdr.version.major, hdr.version.minor)
    if field == "minor_version":
        return hdr.version.minor
    if field == "point_format":
        return hdr.point_format.id
    if field == "point_count":
        return int(hdr.point_count)
    if field == "scales":
        return [float(v) for v in hdr.scales]
    if field == "offsets":
        return [float(v) for v in hdr.offsets]
    if field == "mins":
        return [float(v) for v in hdr.mins]
    if field == "maxs":
        return [float(v) for v in hdr.maxs]
    if field == "vlr_count":
        return len(hdr.vlrs)
    if field == "evlr_count":
        return len(hdr.evlrs) if hdr.evlrs is not None else 0
    if field == "vlr_ids":
        return sorted("%s/%s" % (v.user_id, v.record_id) for v in hdr.vlrs)
    if field == "evlr_ids":
        evlrs = hdr.evlrs or []
        return sorted("%s/%s" % (v.user_id, v.record_id) for v in evlrs)
    if field == "extra_dimension_names":
        return sorted(str(d) for d in las.point_format.extra_dimension_names)
    if field == "dimension_names":
        return sorted(str(d) for d in las.point_format.dimension_names)
    if field == "creation_present":
        return hdr.creation_date is not None
    raise KeyError("unknown las field %r" % field)


# PDAL spells its dimensions in CamelCase ("PointSourceId"); laspy spells the
# same fields snake_case ("point_source_id"). Cases are written in PDAL's
# spelling -- that is what the shipped doc/ pages and the CLI use -- so the
# driver translates. X/Y/Z are deliberately the SCALED doubles: `las["X"]` is
# the raw int32 and a case that asks for Z means metres, not storage units.
_DIM_ALIASES = {
    "gpstime": "gps_time",
    "pointsourceid": "point_source_id",
    "returnnumber": "return_number",
    "numberofreturns": "number_of_returns",
    "scandirectionflag": "scan_direction_flag",
    "edgeofflightline": "edge_of_flight_line",
    "scananglerank": "scan_angle_rank",
    "scanangle": "scan_angle",
    "userdata": "user_data",
    "keypoint": "key_point",
    "scanchannel": "scan_channel",
    "infrared": "nir",
    "classflags": "classification_flags",
}


def _camel_to_snake(name):
    out = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return out.lower()


def las_dim_array(las, dim):
    import numpy as np
    if dim.lower() in ("x", "y", "z"):
        return np.asarray(getattr(las, dim.lower()), dtype="float64")
    known = set(str(d) for d in las.point_format.dimension_names)
    for cand in (dim, _DIM_ALIASES.get(dim.lower()), _camel_to_snake(dim),
                 dim.lower()):
        if cand and cand in known:
            return np.asarray(las[cand])
    raise KeyError("no dimension %r (file has: %s)"
                   % (dim, ", ".join(sorted(known))))


def check_las(case_dir, spec):
    out = []
    path = os.path.join(case_dir, spec["file"])
    if not os.path.exists(path):
        return ["las: %s does not exist" % spec["file"]]
    try:
        las = read_las(path)
    except Exception as exc:  # noqa: BLE001 - a broken file is a candidate failure
        return ["las: %s could not be read back (%s: %s)"
                % (spec["file"], type(exc).__name__, exc)]
    for field, fspec in (spec.get("header") or {}).items():
        try:
            got = las_field(las, field)
        except KeyError as exc:
            out.append("las: %s" % exc)
            continue
        if not isinstance(fspec, dict):
            fspec = {"equals": fspec}
        out += cmp_value(got, fspec, "las %s.%s" % (spec["file"], field))
    for dim, dspec in (spec.get("dims") or {}).items():
        try:
            arr = las_dim_array(las, dim)
        except Exception as exc:  # noqa: BLE001
            out.append("las: %s has no dimension %s (%s)" % (spec["file"], dim, exc))
            continue
        import numpy as np
        for op, where in (("min", "min"), ("max", "max"), ("sum", "sum"),
                          ("mean", "mean")):
            if op in dspec:
                got = float(getattr(np, op)(arr)) if len(arr) else float("nan")
                sub = dspec[op]
                if not isinstance(sub, dict):
                    sub = {"approx": sub, "tol": dspec.get("tol", 1e-6)}
                elif "tol" not in sub and "tol" in dspec:
                    sub = dict(sub, tol=dspec["tol"])
                out += cmp_value(got, sub, "las %s %s.%s" % (spec["file"], dim, where))
        if "values" in dspec:
            want = dspec["values"]
            got = [float(v) for v in arr[:len(want)]]
            tol = dspec.get("tol", 1e-6)
            if len(arr) < len(want):
                out.append("las %s %s: only %d values, expected at least %d"
                           % (spec["file"], dim, len(arr), len(want)))
            else:
                for i, (g, w) in enumerate(zip(got, want)):
                    if not approx(g, w, tol):
                        out.append("las %s %s[%d]: got %r, expected %r +/- %g"
                                   % (spec["file"], dim, i, g, w, tol))
        if "unique" in dspec:
            import numpy as np
            got = sorted(float(v) for v in np.unique(arr))
            out += cmp_value(got, {"equals": sorted(float(v) for v in dspec["unique"])},
                             "las %s %s unique" % (spec["file"], dim))
        if "count_equal" in dspec:
            import numpy as np
            for value, want in dspec["count_equal"].items():
                got = int(np.count_nonzero(arr == float(value)))
                out += cmp_value(got, {"equals": want},
                                 "las %s %s count(==%s)" % (spec["file"], dim, value))
    return out


def check_copc(case_dir, spec):
    """Open a file as COPC with laspy's independent reader and assert its shape.

    `las` (laspy.read) already reads a COPC file as an ordinary LAZ 1.4, so this
    kind exists for the part that is *not* ordinary: the `copc` VLR and the
    octree hierarchy behind it must parse, and a spatial query has to return the
    points inside its box.  A writer that emits a valid LAZ with a malformed or
    absent octree passes `las` and fails here, which is the whole point.

        {"kind": "copc", "file": "out.copc.laz",
         "point_count": {"equals": 1000},
         "queries": [{"bounds": [[0, 3], [0, 3], [0, 3]],
                      "count": {"equals": 64}}]}
    """
    out = []
    # An unknown key here used to be discarded in silence, which is how a
    # `copc` check carrying `extra_dimension_names` -- a key only `las`
    # implements -- sat in the suite asserting nothing at all.  A check that
    # cannot run is worse than no check, so mis-authoring is a hard error.
    unknown = set(spec) - {"kind", "file", "point_count",
                           "hierarchy_entries", "queries"}
    if unknown:
        return ["copc: unsupported key(s) %s -- this check kind reads only "
                "point_count, hierarchy_entries and queries; "
                "extra_dimension_names belongs to a `las` check's header block"
                % ", ".join(sorted(unknown))]
    path = os.path.join(case_dir, spec["file"])
    if not os.path.exists(path):
        return ["copc: %s does not exist" % spec["file"]]
    try:
        import numpy as np
        from laspy.copc import Bounds, CopcReader
    except Exception as exc:  # noqa: BLE001 - a missing reader is a harness fault
        return ["copc: independent COPC reader unavailable (%s: %s)"
                % (type(exc).__name__, exc)]
    try:
        reader = CopcReader.open(path)
    except Exception as exc:  # noqa: BLE001 - a broken file is a candidate failure
        return ["copc: %s did not open as COPC (%s: %s)"
                % (spec["file"], type(exc).__name__, exc)]

    vlrs = [(v.user_id, v.record_id) for v in reader.header.vlrs]
    if ("copc", 1) not in vlrs:
        out.append("copc: %s carries no ('copc', 1) VLR (found %r)"
                   % (spec["file"], vlrs))

    if "point_count" in spec:
        fspec = spec["point_count"]
        if not isinstance(fspec, dict):
            fspec = {"equals": fspec}
        out += cmp_value(int(reader.header.point_count), fspec,
                         "copc %s.point_count" % spec["file"])

    if "hierarchy_entries" in spec:
        fspec = spec["hierarchy_entries"]
        if not isinstance(fspec, dict):
            fspec = {"equals": fspec}
        out += cmp_value(len(list(reader.root_page.entries)), fspec,
                         "copc %s.hierarchy_entries" % spec["file"])

    for i, q in enumerate(spec.get("queries") or []):
        where = "copc %s.queries[%d]" % (spec["file"], i)
        if "bounds" in q:
            (x0, x1), (y0, y1), (z0, z1) = q["bounds"]
            box = Bounds(mins=np.array([float(x0), float(y0), float(z0)]),
                         maxs=np.array([float(x1), float(y1), float(z1)]))
            pts = reader.query(bounds=box)
        else:
            pts = reader.query()
        fspec = q.get("count")
        if fspec is not None:
            if not isinstance(fspec, dict):
                fspec = {"equals": fspec}
            out += cmp_value(len(pts), fspec, where + ".count")
    return out


def check_las_compare(case_dir, spec):
    """Equality of two files over named dimensions.

    Elementwise by default.  With `"unordered": true` the two point sets are
    first ordered identically by the *tuple* of compared dimensions, so what is
    graded is multiset equality -- the right check wherever the stage under test
    is free to reorder points, which `TEST_INTERFACE.md` says is everywhere
    except the one named gate case.  Sorting on the tuple matters: sorting each
    dimension independently would compare marginal distributions and would pass
    for two genuinely different clouds.

    Note that the sort is on exact values, so combining `"unordered"` with a
    non-zero `"tol"` compares tolerantly only *after* an exact ordering.
    """
    import numpy as np
    out = []
    pa = os.path.join(case_dir, spec["a"])
    pb = os.path.join(case_dir, spec["b"])
    for p in (pa, pb):
        if not os.path.exists(p):
            return ["las_compare: %s does not exist" % os.path.basename(p)]
    try:
        a, b = read_las(pa), read_las(pb)
    except Exception as exc:  # noqa: BLE001
        return ["las_compare: a file could not be read back (%s: %s)"
                % (type(exc).__name__, exc)]
    if len(a.points) != len(b.points):
        return ["las_compare: %s has %d points, %s has %d"
                % (spec["a"], len(a.points), spec["b"], len(b.points))]
    tol = spec.get("tol", 0.0)
    cols = []
    for dim in spec.get("dims", ["X", "Y", "Z"]):
        try:
            cols.append((dim, las_dim_array(a, dim), las_dim_array(b, dim)))
        except Exception as exc:  # noqa: BLE001
            out.append("las_compare: dimension %s unreadable (%s)" % (dim, exc))
    if spec.get("unordered") and cols:
        # np.lexsort takes its keys least-significant-FIRST (the last key is
        # the primary one), so reverse to make dims[0] primary.
        ia = np.lexsort(tuple(c[1] for c in reversed(cols)))
        ib = np.lexsort(tuple(c[2] for c in reversed(cols)))
        cols = [(d, va[ia], vb[ib]) for d, va, vb in cols]
    for dim, va, vb in cols:
        if tol:
            bad = int(np.count_nonzero(np.abs(va.astype("float64")
                                              - vb.astype("float64")) > tol))
        else:
            bad = int(np.count_nonzero(va != vb))
        if bad:
            out.append("las_compare: %s differs in %d of %d points"
                       % (dim, bad, len(va)))
    return out



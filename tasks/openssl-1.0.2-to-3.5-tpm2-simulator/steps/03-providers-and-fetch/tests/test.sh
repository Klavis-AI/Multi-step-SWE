#!/usr/bin/env bash
# PRODUCT SCORING (2026-10-13): the reward is now T1 x T2 -- T1 = this
# step's own gates (`migrated`), T2 = behaviour and the retained gates of
# earlier steps at their old relative weights -- see `Product scoring` at
# the reward.  Any weight or floor arithmetic stated below describes the
# superseded weighted sum.
# Step 3 verifier -- the library context, the fetch, and a digest state the
# engine can no longer see, against OpenSSL 3.0.17.
#
# Authoring source.  build/mkstep.sh installs this as
# steps/03-providers-and-fetch/tests/test.sh; edit it here and regenerate,
# never edit the copy under tasks/.
#
#
# WHAT THIS STEP IS
#
# Steps 1 and 2 moved the engine off its vendored 1.0.2b, through the accessors
# 1.1.0 published, onto 1.1.1's private DRBG and the library's own ECDSA.  In
# all of it the engine still got its algorithms the way a program got them in
# 1998: EVP_sha256() returned a pointer to a static record inside libcrypto,
# and the engine read the private bytes behind an EVP_MD_CTX whenever the TPM
# asked it to put a hash sequence somewhere.
#
# 3.0 is where both of those stop working.  Algorithms come from providers now,
# and the way to ask for one is EVP_MD_fetch against a library context -- an
# object with a lifetime, which the caller owns, unloads and frees.  And the
# state behind an EVP_MD_CTX moved into the provider: for a provided SHA-256,
# EVP_MD_CTX_get0_md_data() is NULL, EVP_MD_meth_get_app_datasize() is 0, and
# nothing in EVP_MD_CTX_gettable_params(), EVP_MD_CTX_settable_params(),
# EVP_MD_settable_ctx_params() or EVP_MD_gettable_ctx_params() names the
# running state -- for SHA-256 each of those four returns an empty list.  The
# measurement is build/probe/ossl30state.c and build/logs/ossl30state.log,
# written up as NOTES-authoring.md § 7.3.  There is no picture of a digest left
# to take, at any price, through any public API.
#
# That second half is what makes this step a leap rather than a rename.  The
# engine's hash sequence state is a 272-byte field inside a structure the TPM
# above it relocates with memcpy, duplicates, writes out as a context blob and
# abandons with memset -- CpriHash.c's OSSL_HASH_STATE, whose whole design is
# that the digest is a VALUE living in the caller's storage.  Every one of
# those operations is in the corpus, deliberately: `hashmove`, `hashmove2`,
# `hashmove3`, `hashmovedrop`, `hashmoveafter`, `hashcopy` and `hashexport` in
# the engine suite, `e2eseqctx` over the wire.  A port that keeps a live
# EVP_MD_CTX pointer in that field fails them, and it fails them in a way that
# no amount of reference counting repairs: `hashmoveafter` relocates a state,
# completes the ORIGINAL, then feeds the copy the same tail and requires the
# two digests to agree, which defeats copy-on-relocation; `hashmove2` completes
# a three-deep relocation chain in reverse order, which defeats freeing the
# parent on completion; `hashmovedrop` memsets the original to zero and never
# completes it, which defeats freeing on abandonment.
#
# So the step is: own a library context, load a provider into it explicitly,
# fetch the digests from it by name once rather than per operation, and find a
# representation for a hash sequence state that is still a value under memcpy
# when the bytes of the digest cannot be obtained.
#
#
# HOW IT IS SCORED
#
#     reward = 0.40 * behaviour + 0.52 * migrated + 0.08 * retained
#
#         behaviour = mean( breadth, worst_family )    -- exactly step 1's
#         migrated  = mean( the six bookkeeping gates ) / 2
#                     + the sequence gate / 2
#         retained  = the fraction of the 13 gates steps 01-02 introduced
#                     that still pass
#
# `migrated` is the one departure from steps 1 and 2, which weigh their gates
# equally.  Six of this step's seven are bookkeeping and one is the step's
# whole difficulty; the argument for splitting 0.52 down the middle rather
# than into sevenths is above the computation itself.
#
# The same three-way split and the same weights as step 2, for the same reason
# and with a great deal more room.  Step 2's finished tree, dropped on 3.0.17
# untouched, still compiles and still links -- EVP_MD_CTX_md and
# EVP_MD_meth_get_app_datasize are deprecated at 3.0, not removed -- so it gets
# through P2 and P3 and is scored on what it can still do.  What it can still
# do was measured (NOTES § 7.4):
#
#     engine 1445/1676 = 0.862172      e2e 842/1048 = 0.803435
#     breadth = 0.832804      worst family = e2ehashseq at 0/40 = 0.000000
#     behaviour = 0.416402
#     reward = 0.40*0.416402 + 0.52*0.000 + 0.08*1.000 = 0.246561
#
# The e2e half of that fell when the driver stopped misparsing response handle
# areas (NOTES § 7.11.1): 856/1047 became 842/1048.  Against the recording the
# round-4 figure was measured on, thirteen rows changed -- seven `e2ehmac` and
# six `e2eseqctx`, the two families the leak reached -- and one row was added,
# `e2ehmac/ok/127`, which had previously not existed because the session ran out
# of object memory before reaching it.  The matched count fell by fourteen
# rather than by thirteen because the e2e corpus is replayed as sessions, so a
# row whose answer changes can carry the row after it.  The floor got lower by
# being measured correctly, which is the only direction a recorder fix may move
# it.
#
# Comfortably under item 6's 0.5, and not by an accident of weighting: the
# `worst_family` term is 0 because a whole family of the corpus goes to nothing
# the moment the digest state stops being readable, which is the step.  Every
# one of the seven gates below is false on that tree, so `migrated` is 0 for
# it whichever way the seven are weighed, and `retained` is 1 because nothing
# about steps 1 and 2 has been undone.  The seventh gate was added after the
# round-1 review and does not move the floor: that tree fails it too, for the
# same reason it takes worst_family to zero.
#
# 0.08 over 13 retained gates prices one regression at 0.006.  That is smaller
# than step 2's 0.013 and it is the right direction: the further up the ladder,
# the more inherited properties there are, and a step whose retained family
# grows without its weight growing is a step that does not start paying for its
# predecessors.  What the weight has to do is make a regression visible and not
# let it buy anything, and 0.006 against a 1.000 is visible.  Raising it would
# start to matter at the floor -- step 2's tree collects `retained` in full, so
# every point of weight moved into that family is a point added to 0.247.
#
#
# WHAT DOES NOT FLIP, AND THE ONE THING THAT CANNOT BE PRESERVED
#
# Nothing in either corpus is re-recorded at this step.  The engine computes
# the same digests from a provider as it did from the built-in table -- SHA-256
# is SHA-256 -- and the sequence families are recordings of what a correct
# sequence state does, not of how it is stored.
#
# There is one property of the baseline's sequence object that no port can
# carry to 3.0, and it is worth naming here because it is a real difference and
# not a defect:
#
#     The bytes in the sequence object can no longer be libcrypto's own.
#
# The baseline marshals the digest's private state out from behind an
# EVP_MD_CTX and into the sequence object, which is why the object survives
# being moved: the bytes ARE the state and they travel with it.  3.0 publishes
# no way to read them, so no 3.0 port can build that object, and whatever a
# port puts there instead refers to state the running process holds.
#
# What does NOT follow, and was claimed here before the round-1 review caught
# it, is anything about surviving a restart.  On this codebase the baseline
# cannot do that either: src/simulator/TPMCmds.c calls TPM_Manufacture at every
# process start (and TPM_TearDown followed by another manufacture after that),
# so every launch is a factory-fresh TPM, the hierarchy proofs a context blob
# is encrypted under are redrawn, and a blob from a previous process is not
# loadable whatever is inside it.  Both corpora are single-process for the same
# reason -- it is the only way either could have been recorded -- and the
# property they score is relocation within one process, which is required and
# is what the four sequence families measure.
#
#
# WHAT SCORES ZERO OUTRIGHT
#
# The same five, inherited unchanged and filed under step 01, because they are
# step 01's statements:
#
#   P0  /app arrived intact               environment failure, not the candidate
#   P1  the image binds OpenSSL 3.0.17    environment failure, not the candidate
#   P2  the tree configures and builds    nothing to measure
#   P3  every built object gets OpenSSL from the loader, and from /usr/local
#   P4  an outside consumer still compiles against the public headers
#       (not a precondition: it costs the engine corpus, as at steps 1 and 2)
#
#
# THE SEVEN GATES
#
# Every one is false on step 2's finished tree, which is what rule 5 asks of
# the migrated-ness family: the predecessor must fail them completely rather
# than collect credit for checks that are vacuously true.
#
#   1  the engine owns a library context      OSSL_LIB_CTX_new, from init,
#                                             and one really was made there
#   2  and gives it back                      OSSL_LIB_CTX_free, from stop,
#                                             on the one it made, none left live
#   3  the provider is loaded by name         load from init into the engine's
#                                             own context, and one really was
#                                             given back at stop
#   4  digests come from a fetch against that context, and the built-in
#      getters are gone from the sources and from the imports
#   5  what was fetched is held: the long half of a fixed workload provokes no
#      new fetches, and no reference is still held at the end
#   6  the digest's private state is neither read nor reached around, in the
#      sources or in the imports
#   7  a sequence state is still a value after the layers above move it
#
# Gates 1-5 read a run-time probe as well as the scans, and gate 7 reads the
# corpus.  Both additions came out of the round-1 static review; the argument
# for each is above the gate itself, and the short version is that three of
# this step's requirements are about WHICH OBJECT a call was made against and
# one is about HOW OFTEN, and a scan can answer neither.  A tree that creates a
# context, loads a provider into it, and then calls EVP_MD_fetch(NULL, ...)
# does all three named things and takes its digests from the process default.
#
# Gate 6 is the one with two halves, and they have to be one gate.  Its first
# half -- no EVP_MD_CTX_md, no EVP_MD_CTX_get0_md_data, no
# EVP_MD_meth_get_app_datasize -- is the accessors 3.0 emptied out, and step 2's
# tree imports two of the three, so that half fails on the predecessor.  Its
# second half -- no SHA1_Init/SHA256_Init/SHA512_Init and the rest of the
# low-level digest API -- is TRUE of step 2's tree, which has never called any
# of them, and would be a free check as a gate of its own.  Conjoined it is not
# free, and it closes the one escape hatch this step has: SHA256_CTX is a
# published struct with a published layout at 3.0, still there, still
# deprecated-not-removed, and an engine that abandons EVP for the low-level
# functions gets its memcpy-able digest state back and passes every behaviour
# family in the corpus without doing the step at all.  That port is not a bad
# guess -- it is what the code wanted -- and the requirement that refuses it is
# in the instruction in the same words: the digests come from the provider.
#
# Gate 5 is reachability asked negatively, and the shape of the question is
# forced by what a correct port is allowed to look like.  "Fetched once" has
# two honest spellings: fetch every digest in the hash service's startup and
# cache them (the golden), or fetch lazily in the lookup the three call sites
# already go through and cache there.  The second one puts EVP_MD_fetch one hop
# below _cpri__StartHash, so a gate asking StartHash not to reach the fetch
# would fail it for choosing the other correct shape.  What both correct shapes
# have in common, and what a fetch-per-operation port cannot have, is on the
# other side of the transaction: a fetched EVP_MD is reference counted and has
# to be given back, so a port that takes one per operation must also give one
# back per operation.  So the AST half asks that EVP_MD_free is called
# somewhere and is NOT reached from any of the nine entry points that do hash
# work.  A per-operation port that frees correctly fails it at the entry point.
#
# A per-operation port that LEAKS instead does not fail it, and that is the
# hole the review found: such a port reaches EVP_MD_free from nowhere, so one
# EVP_MD_free(NULL) in the shutdown path satisfies "is called" while every
# operation has taken a reference and dropped it.  The probe closes it by
# measuring the rate directly, as the difference between two halves of a fixed
# workload, and by checking that the count of references taken equals the count
# given back.
#
# Gates 1 and 2 are separate, and 3 is not split the same way, on purpose.  The
# context and the provider are one decision -- a provider is loaded INTO a
# context, and a port with one and not the other has not got a working fetch --
# whereas creating a context and releasing it are two, and "created but never
# released" is the common half-done shape that is worth naming as such in the
# log rather than folding into a pass or a fail of something else.
#
# Gate 7 is the one gate that measures nothing new.  It re-reads the cases the
# behaviour half already scored that relocate, duplicate or abandon a hash
# sequence state -- the 105 cases of the engine's `hashstate` family whose
# operation is a move, and the 111 `e2eseqctx` cases that save a sequence's
# context and load it back -- and what it adds is weight, not evidence.  The reason is that the other six are all
# bookkeeping, and a tree can do the whole of the bookkeeping without solving
# what the instruction calls this step's whole difficulty; before this gate
# existed that tree collected the entire 0.52 and lost only the worst_family
# term.  It now costs half of it.
#
# Which cases, and not which families, because two of the four families the
# gate first read are not about relocation at all and a third is only mostly
# about it.  The note above the gate has the detail.  The point of the
# narrowing is that the gate's name should describe what fails it: a port that
# drops a one-shot SHA-1 has broken something, and it has not broken this.

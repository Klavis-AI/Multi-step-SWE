//! Group `basicutil`: peripheral coverage of `tor-basic-utils`, the shared
//! utility crate this checkpoint introduces to hold the decorrelated-jitter
//! retry schedule.  The schedule itself is graded by `retrydelay`; this group
//! covers the crate's other two documented public items, so that the crate is
//! graded as a whole rather than as a single function.
//!
//! Graded items: `tor_basic_utils::skip_fmt` and
//! `tor_basic_utils::define_accessor_trait!`.

use std::fmt;

use tor_basic_utils::{define_accessor_trait, skip_fmt};

/// A value whose `Debug` deliberately elides one field, the way a struct
/// holding key material does.
struct Elided {
    visible: usize,
    secret: [u8; 32],
}

impl fmt::Debug for Elided {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        write!(f, "Elided {{ visible: {:?}, secret: ", self.visible)?;
        skip_fmt(&self.secret, f)?;
        write!(f, " }}")
    }
}

/// A newtype whose entire `Debug` output is delegated to `skip_fmt`.
struct OnlyElided<T>(T);

impl<T> fmt::Debug for OnlyElided<T> {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        skip_fmt(&self.0, f)
    }
}

#[test]
fn basicutil__skip_fmt_renders_exactly_two_dots_for_any_value() {
    // The point of the helper is that the *value* never reaches the output, so
    // wildly different values of wildly different types render identically.
    assert_eq!(format!("{:?}", OnlyElided([0u8; 32])), "..");
    assert_eq!(format!("{:?}", OnlyElided([0xffu8; 32])), "..");
    assert_eq!(format!("{:?}", OnlyElided("a secret string")), "..");
    assert_eq!(format!("{:?}", OnlyElided(12345_u64)), "..");
    assert_eq!(format!("{:?}", OnlyElided(())), "..");

    // The alternate ("{:#?}") form is elided too: there is nothing to expand.
    assert_eq!(format!("{:#?}", OnlyElided([1u8, 2, 3])), "..");
}

#[test]
fn basicutil__skip_fmt_elides_one_field_and_leaves_its_siblings_visible() {
    let a = Elided {
        visible: 7,
        secret: [0xaa; 32],
    };
    let b = Elided {
        visible: 7,
        secret: [0x55; 32],
    };

    assert_eq!(format!("{:?}", a), "Elided { visible: 7, secret: .. }");
    // The visible field still varies...
    assert_eq!(
        format!(
            "{:?}",
            Elided {
                visible: 0,
                secret: [0xaa; 32]
            }
        ),
        "Elided { visible: 0, secret: .. }"
    );
    // ...while two records differing only in the elided field are
    // indistinguishable in the output.
    assert_eq!(format!("{:?}", a), format!("{:?}", b));
    assert!(!format!("{:?}", a).contains("170"));
    assert!(!format!("{:?}", b).contains("85"));
}

// A trait generated by the macro: it names two fields of different types, and
// the macro supplies both the supertrait bounds and the accessor bodies.
define_accessor_trait! {
    pub trait Sizes {
        label: String,
        count: usize,
    }
}

struct Wide {
    label: String,
    count: usize,
    #[allow(dead_code)]
    unrelated: Vec<u8>,
}

impl AsRef<String> for Wide {
    fn as_ref(&self) -> &String {
        &self.label
    }
}
impl AsRef<usize> for Wide {
    fn as_ref(&self) -> &usize {
        &self.count
    }
}
impl Sizes for Wide {}

struct Narrow {
    label: String,
    count: usize,
}

impl AsRef<String> for Narrow {
    fn as_ref(&self) -> &String {
        &self.label
    }
}
impl AsRef<usize> for Narrow {
    fn as_ref(&self) -> &usize {
        &self.count
    }
}
impl Sizes for Narrow {}

#[test]
fn basicutil__define_accessor_trait_generates_borrowing_accessors() {
    let w = Wide {
        label: "consensus".to_owned(),
        count: 3,
        unrelated: vec![1, 2, 3],
    };

    // The generated accessors return references to the fields named in the
    // macro invocation, selected by type through `AsRef`.
    let label: &String = w.label();
    let count: &usize = w.count();
    assert_eq!(label, "consensus");
    assert_eq!(*count, 3);
    // They really borrow: the addresses match the struct's own fields.
    assert!(std::ptr::eq(label, &w.label));
    assert!(std::ptr::eq(count, &w.count));
}

#[test]
fn basicutil__the_generated_trait_is_usable_as_a_generic_bound() {
    // Lower-level code takes any implementor without knowing the concrete
    // struct, which is the reason the macro exists.
    fn describe<V: Sizes>(v: &V) -> String {
        format!("{}:{}", v.label(), v.count())
    }

    let wide = Wide {
        label: "microdesc".to_owned(),
        count: 12,
        unrelated: Vec::new(),
    };
    let narrow = Narrow {
        label: "certs".to_owned(),
        count: 0,
    };

    assert_eq!(describe(&wide), "microdesc:12");
    assert_eq!(describe(&narrow), "certs:0");

    // The trait's supertrait bounds are the `AsRef`s the macro asked for, so a
    // `&dyn` view can still reach both fields.
    let erased: &dyn Sizes = &narrow;
    assert_eq!(erased.label(), "certs");
    assert_eq!(*erased.count(), 0);
}
